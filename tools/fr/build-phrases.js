#!/usr/bin/env node
/* build-phrases.js: francais/data/phrases.js (window.FR_PHRASES) for Phrases,
 * from tools/fr/src/phrases/*.json: { fr, en, alt?, th, b, t, n? }, in the
 * order written within each tier (tier 1 first). Rejects dashes, duplicates,
 * phrases over 8 words, bad bands, tiers or themes. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const dir = path.join(__dirname, 'src', 'phrases');
const THEMES = ['saluer', 'moi', 'conversation', 'sentiments', 'temps', 'meteo', 'maison', 'magasin', 'aide', 'travail', 'fete'];
const out = [], bad = [], seen = {};
(fs.existsSync(dir) ? fs.readdirSync(dir) : []).filter(f => f.endsWith('.json')).sort().forEach(f => {
  JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).forEach((p, i) => {
    const at = `${f}#${i} ${p.fr}`;
    if (!p.fr || !p.en || !p.th) return bad.push(at + ': needs fr, en, th');
    if (THEMES.indexOf(p.th) === -1) return bad.push(at + ': theme ' + p.th);
    if (['A1', 'A2', 'B1', 'B2'].indexOf(p.b) === -1) return bad.push(at + ': band');
    if ([1, 2, 3].indexOf(p.t) === -1) return bad.push(at + ': tier');
    if (/[–—]|\s-\s/.test(JSON.stringify(p))) return bad.push(at + ': dash');
    if (p.fr.replace(/[.,;:!?]/g, '').trim().split(/\s+/).filter(w => w !== '').length > 8) return bad.push(at + ': over 8 words');
    if (seen[p.fr]) return bad.push(at + ': duplicate');
    seen[p.fr] = 1;
    out.push(Object.assign({ _o: out.length }, p));
  });
});
out.sort((a, b) => a.t - b.t || a._o - b._o);
out.forEach(p => delete p._o);
bad.forEach(b => console.log('  ✗ ' + b));
if (out.length)
  fs.writeFileSync(path.join(ROOT, 'francais', 'data', 'phrases.js'),
    `/* GENERATED by tools/fr/build-phrases.js from tools/fr/src/phrases/. Do not edit. ${out.length} phrases. */\n` +
    '(function (w) {\nw.FR_PHRASES = [\n' + out.map(p => JSON.stringify(p)).join(',\n') +
    '\n];\nif (typeof module !== "undefined" && module.exports) module.exports = w.FR_PHRASES;\n})(typeof window !== "undefined" ? window : globalThis);\n');
console.log(out.length + ' phrases, ' + bad.length + ' rejected');
