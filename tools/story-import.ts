// Brings the rebuild's serial chapters into the ORIGINAL app's data as lazily loaded files.
//   data/story/index.js (window.STORY_INDEX), data/story/<band>.js (window.STORY_<BAND>)
// Run:  nice npx tsx tools/story-import.ts
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { castNames, loadGraph, tagOptions, type GraphNode } from '../lib/graph';
import { splitSentences, tagSentence } from '../lib/tagger';
import { DAY_WORDS, lineBody, placeQuestions, splitLines, toLines, type GlossPair, type Q } from './story/split';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const t0 = Date.now();
const gdir = join(ROOT, 'app/content/graph');
const graph = loadGraph(readdirSync(gdir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort()
  .map((f) => JSON.parse(readFileSync(join(gdir, f), 'utf8')) as GraphNode[]));
const udir = join(ROOT, 'app/content/units');
const units = readdirSync(udir).filter((f) => /^u\d+\.json$/.test(f)).sort().map((f) => JSON.parse(readFileSync(join(udir, f), 'utf8')));
const opts = tagOptions(graph, { names: castNames(units.map((u) => u.storyArc ?? '').join(' ')) });
const bandOf = (u: string) => {
  const b = units.find((x) => x.id === u)?.band;
  if (b) return b as string;
  const n = +u.slice(1);
  return n <= 14 ? 'A1' : n <= 27 ? 'A2' : n <= 40 ? 'B1' : n <= 52 ? 'B2' : 'C1';
};

const sdir = join(ROOT, 'app/content/story');
const files = readdirSync(sdir).filter((f) => /^ch\d+\.json$/.test(f)).sort();
type Stat = { chapters: number; words: number; split: number; parts: number; qs: number; unlocated: number; longest: number; viaQuestion: number };
const stats: Record<string, Stat> = {};
const out: Record<string, any[]> = {};
const index: any[] = [];
const retag: string[] = [];
const issues: string[] = [];

files.forEach((f, k) => {
  const ch = JSON.parse(readFileSync(join(sdir, f), 'utf8'));
  const band = bandOf(ch.unit);
  const lines = toLines(ch.text);
  const req = new Set<string>(), lex = new Set<string>(), lemmas = new Set<string>();
  for (const l of lines) for (const s of splitSentences(lineBody(l.text))) {
    const r = tagSentence(s, opts);
    for (const n of r.requires) (n.startsWith('l:') ? lex : req).add(n);
    for (const t of r.tokens) if (!t.punct && t.pos !== 'propn' && t.pos !== 'punct' && t.pos !== 'unknown' && t.lemma) lemmas.add(t.lemma.toLowerCase());
  }
  const stored = new Set<string>(ch.requires ?? []);
  const extra = [...req].filter((n) => !stored.has(n)).sort();
  if (extra.length) retag.push(`${ch.id} (${ch.unit}): ${extra.join(', ')}`);
  const words = lines.reduce((a, l) => a + l.words, 0);
  const parts = splitLines(lines, DAY_WORDS[band]);
  const gloss: GlossPair[] = ch.gloss ?? [];
  const placed = placeQuestions((ch.questions ?? []) as Q[], lines, parts, gloss);
  const last = parts.length - 1;
  const outParts = parts.map((p, pi) => ({
    text: p.map((i) => lines[i].text).join('\n'),
    questions: placed.filter((x) => x.part === pi).map((x) => ({ ...x.q, longest: x.longest })),
    recap: null,
    hook: pi === last ? ch.hook ?? null : null,
  }));
  if (outParts.some((p) => !p.text.trim())) issues.push(`${ch.id}: empty part`);
  const n = k + 1;
  (out[band] ??= []).push({
    id: ch.id, unit: ch.unit, n, title: ch.title, band, words, parts: outParts, gloss,
    rereadQuestions: ch.rereadQuestions ?? [], requires: [...req].sort(), lexemes: [...lex].sort(), lemmas: [...lemmas].sort(),
  });
  index.push({ id: ch.id, unit: ch.unit, band, title: ch.title, words, parts: parts.length, file: `data/story/${band.toLowerCase()}.js` });
  const s = (stats[band] ??= { chapters: 0, words: 0, split: 0, parts: 0, qs: 0, unlocated: 0, longest: 0, viaQuestion: 0 });
  s.chapters++; s.words += words; s.parts += parts.length; if (parts.length > 1) s.split++;
  for (const x of placed) { s.qs++; if (!x.located) s.unlocated++; if (x.longest) s.longest++; if (x.how === 'question') s.viaQuestion++; }
});

mkdirSync(join(ROOT, 'data/story'), { recursive: true });
const sizes: string[] = [];
const write = (name: string, body: string) => { const p = join(ROOT, 'data/story', name); writeFileSync(p, body); sizes.push(`${name}: ${(statSync(p).size / 1024).toFixed(0)} KB`); };
for (const b of Object.keys(out)) {
  write(`${b.toLowerCase()}.js`, `/* GENERATED by tools/story-import.ts. Do not edit. */\nwindow.STORY_${b} = [\n${out[b].map((c) => JSON.stringify(c)).join(',\n')}\n];\n`);
}
write('index.js', `/* GENERATED by tools/story-import.ts. Do not edit. */\nwindow.STORY_INDEX = [\n${index.map((c) => JSON.stringify(c)).join(',\n')}\n];\n`);

const pct = (a: number, b: number) => (b ? (100 * a / b).toFixed(1) : '0') + '%';
const order = ['A1', 'A2', 'B1', 'B2', 'C1'].filter((b) => stats[b]);
const tot = order.reduce((a, b) => ({ q: a.q + stats[b].qs, u: a.u + stats[b].unlocated }), { q: 0, u: 0 });
const md = ['# Story import (Stage 4 data)', '', 'Generated by `tools/story-import.ts`. Band comes from each unit\'s `band` field. Reading-day words: ' + order.map((b) => `${b} ${DAY_WORDS[b]}`).join(', ') + '.', '',
  '| band | chapters | words | chapters split | parts | questions | unlocated (last part) | placed via question words | correct option longest |', '|---|---|---|---|---|---|---|---|---|',
  ...order.map((b) => { const s = stats[b]; return `| ${b} | ${s.chapters} | ${s.words} | ${s.split} | ${s.parts} | ${s.qs} | ${s.unlocated} (${pct(s.unlocated, s.qs)}) | ${s.viaQuestion} | ${s.longest} (${pct(s.longest, s.qs)}) |`; }),
  '', `Total unlocated: ${tot.u} of ${tot.q} (${pct(tot.u, tot.q)}). Chance for the longest-option share is about 25% with four options.`, '',
  '## File sizes', '', ...sizes.map((s) => `- ${s}`), '',
  `## Re-tag found a require not in the chapter's stored requires (${retag.length} chapters)`, '', ...(retag.length ? retag.map((r) => `- ${r}`) : ['None.']), '',
  ...(issues.length ? ['## Issues', '', ...issues.map((i) => `- ${i}`), ''] : [])];
writeFileSync(join(ROOT, 'docs/plan-2026-11-04/story-import.md'), md.join('\n'));
console.log(md.join('\n'));
console.log(`\n${((Date.now() - t0) / 1000).toFixed(1)}s, rss ${(process.memoryUsage().rss / 1048576).toFixed(0)} MB`);
