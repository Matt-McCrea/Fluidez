#!/usr/bin/env python3
"""Voices for the example conversations in Juegos (es) and Líofa (ga), from
Microsoft's neural voices (edge-tts), made at build time and shipped as mp3.
One voice per role, so the two speakers always sound different: a woman and a
man, the role's own hint ("You (a man)") deciding when it gives one.
Clips are made once into tools/<lang>/vendor/convo-clips/ (a rerun only makes
new lines), then packed into a few bundles, <app>/audio/c-<hash>.bin.
  tools/ar/vendor/venv/bin/python tools/build-convo-audio.py es|ga
Writes the bundles and <data>/convo-audio.js ("<convo id>#<line>": "audio/x.bin#off,len")."""
import asyncio, hashlib, json, os, sys
import edge_tts

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANG = sys.argv[1] if len(sys.argv) > 1 else ''
CFG = {
    'es': dict(field='es', app='juegos', data='data', glob='ES_CONVO_AUDIO', name='Juegos',
               f='es-CO-SalomeNeural', m='es-CO-GonzaloNeural', voices='es-CO (Colombia)'),
    'ga': dict(field='ga', app='gaeilge', data='gaeilge/data', glob='GA_CONVO_AUDIO', name='Líofa',
               f='ga-IE-OrlaNeural', m='ga-IE-ColmNeural', voices='ga-IE'),
}.get(LANG)
if not CFG:
    print('usage: build-convo-audio.py es|ga'); sys.exit(2)
AUD = os.path.join(HERE, LANG, 'vendor', 'convo-clips')
PACK = os.path.join(ROOT, CFG['app'], 'audio')
OUT = os.path.join(ROOT, CFG['data'], 'convo-audio.js')
PER = 40

def gender(role):
    r = (role or '').lower()
    if '(a man)' in r or r.startswith('man') or ' man' in r: return 'm'
    if '(a woman)' in r or 'woman' in r: return 'f'
    return None

def voices_for(c):
    ga, gb = gender(c['roles'].get('a')), gender(c['roles'].get('b'))
    a = ga or ('m' if gb == 'f' else 'f')
    b = gb or ('f' if a == 'm' else 'm')
    if a == b: b = 'f' if a == 'm' else 'm'
    return {'a': CFG[a], 'b': CFG[b]}

def clip_name(text, voice):
    return hashlib.sha1((text + '|' + voice).encode('utf-8')).hexdigest()[:12] + '.mp3'

async def one(text, voice, sem, fails):
    fn = os.path.join(AUD, clip_name(text, voice))
    if os.path.exists(fn) and os.path.getsize(fn) > 1000: return
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(text, voice, rate='-8%').save(fn)
                if os.path.getsize(fn) > 1000: return
            except Exception:
                pass
            await asyncio.sleep(2 + attempt * 3)
        fails.append(text)

async def main():
    os.makedirs(AUD, exist_ok=True)
    C = json.load(open(os.path.join(HERE, 'convos', LANG + '.json'), encoding='utf-8'))
    jobs = []                                   # (key, text, voice)
    for c in C:
        vs = voices_for(c)
        for i, l in enumerate(c['lines']):
            jobs.append((c['id'] + '#' + str(i), l[CFG['field']], vs[l['who']]))
    sem, fails = asyncio.Semaphore(2), []
    await asyncio.gather(*(one(t, v, sem, fails) for t, v in sorted({(j[1], j[2]) for j in jobs})))
    os.makedirs(PACK, exist_ok=True)
    m, keep = {}, set()
    good = [j for j in jobs if os.path.exists(os.path.join(AUD, clip_name(j[1], j[2]))) and os.path.getsize(os.path.join(AUD, clip_name(j[1], j[2]))) > 1000]
    for n in range(0, len(good), PER):
        chunk, blob, refs = good[n:n + PER], bytearray(), []
        for key, t, v in chunk:
            data = open(os.path.join(AUD, clip_name(t, v)), 'rb').read()
            refs.append((key, len(blob), len(data)))
            blob += data
        name = 'c-' + hashlib.sha1(bytes(blob)).hexdigest()[:10] + '.bin'
        keep.add(name)
        fn = os.path.join(PACK, name)
        if not os.path.exists(fn): open(fn, 'wb').write(blob)
        for key, off, ln in refs: m[key] = 'audio/%s#%d,%d' % (name, off, ln)
    for f in os.listdir(PACK):
        if f.startswith('c-') and f not in keep: os.remove(os.path.join(PACK, f))
    js = ('/* %s conversation audio: generated by tools/build-convo-audio.py. Voices: Microsoft neural TTS\n'
          ' * (%s), one per role. Do not edit. */\n'
          '(function (root) {\n  var A = %s;\n'
          '  if (typeof module !== "undefined" && module.exports) module.exports = A;\n  else root.%s = A;\n})(this);\n'
          ) % (CFG['name'], CFG['voices'], json.dumps(m, ensure_ascii=False, separators=(',', ':')), CFG['glob'])
    open(OUT, 'w', encoding='utf-8').write(js)
    print(len(jobs), 'lines,', len(m), 'clips,', len(fails), 'failed')
    if fails: print('failed:', ' | '.join(fails[:10]), file=sys.stderr)

if __name__ == '__main__':
    asyncio.run(main())
