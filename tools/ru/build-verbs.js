#!/usr/bin/env node
/* Svobodno verbs: tools/ru/src/verbs.txt (the list, by hand) + OpenRussian forms
 * (tools/ru/vendor/verbs.csv, CC BY-SA 4.0) into russkiy/data/verbs.js, gated.
 *   node tools/ru/build-verbs.js
 * Each verb: { inf, en, asp: 'i'|'p', pair, pres|fut: [я ты он мы вы они], past: {m,f,n,pl},
 * imp: {sg,pl}, motion?: 'multi'|'uni' }. Stress is the combining acute. Overrides in
 * src/verb-fix.json win over the source, form by form. */
'use strict';
const fs = require('fs');
const path = require('path');
const RU = require('../../russkiy/js/ru-text.js');
const ROOT = path.join(__dirname, '..', '..');

function tsv(file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/).filter(Boolean);
  const head = lines[0].split('\t');
  return lines.slice(1).map(l => { const c = l.split('\t'), o = {}; head.forEach((h, i) => { o[h] = (c[i] || '').trim(); }); return o; });
}
const SRC = tsv(path.join(__dirname, 'vendor', 'verbs.csv'));
const BY = {};
SRC.forEach((r, i) => { if (!BY[r.bare]) BY[r.bare] = Object.assign({ rank: i }, r); });
let FIX = {};
try { FIX = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'verb-fix.json'), 'utf8')); } catch (e) {}

// one acute only, and none on a monosyllable or on ё
function S(s) {
  s = RU.fromApostrophe(String(s || '').split(/[,;]/)[0].trim());
  const bare = s.replace(/́/g, '');
  if ((bare.match(/[аеёиоуыэюя]/g) || []).length < 2 || /ё/.test(bare)) return bare;
  return s;
}
const MOTION = { 'ходить': 'multi', 'идти': 'uni', 'ездить': 'multi', 'ехать': 'uni', 'летать': 'multi', 'лететь': 'uni',
  'плавать': 'multi', 'плыть': 'uni', 'носить': 'multi', 'нести': 'uni', 'водить': 'multi', 'вести': 'uni',
  'возить': 'multi', 'везти': 'uni', 'бегать': 'multi', 'бежать': 'uni' };

let errs = 0;
const out = [];
fs.readFileSync(path.join(__dirname, 'src', 'verbs.txt'), 'utf8').split('\n').forEach(line => {
  if (!line.trim() || line[0] === '#') return;
  const [ws, en] = line.split('|').map(s => s.trim());
  const pair = ws.split(/\s+/);
  pair.forEach((w, k) => {
    const r = BY[w];
    if (!r) { errs++; console.log('not in OpenRussian: ' + w); return; }
    const fx = FIX[w] || {};
    const asp = fx.asp || (pair.length === 2 ? (k === 0 ? 'i' : 'p') : (r.aspect === 'perfective' ? 'p' : 'i'));
    const pf = ['presfut_sg1', 'presfut_sg2', 'presfut_sg3', 'presfut_pl1', 'presfut_pl2', 'presfut_pl3'].map(c => S(r[c]));
    const v = {
      inf: S(r.accented), en: fx.en || en, asp: asp, rank: r.rank,
      pair: pair.length === 2 ? pair[1 - k] : '',
      past: { m: S(r.past_m), f: S(r.past_f), n: S(r.past_n), pl: S(r.past_pl) },
      imp: { sg: S(r.imperative_sg), pl: S(r.imperative_pl) }
    };
    v[asp === 'i' ? 'pres' : 'fut'] = fx.pf || pf;
    if (fx.past) Object.assign(v.past, fx.past);
    if (fx.imp) Object.assign(v.imp, fx.imp);
    if (MOTION[w]) v.motion = MOTION[w];
    if (w === 'быть') { v.pres = ['', '', 'есть', '', '', '']; v.fut = ['бу́ду', 'бу́дешь', 'бу́дет', 'бу́дем', 'бу́дете', 'бу́дут']; }
    // gate: every form there, stressed where it has two vowels or more
    const forms = [v.inf].concat(v.pres || v.fut).concat([v.past.m, v.past.f, v.past.n, v.past.pl]).filter(f => f !== '');
    if (w !== 'быть' && forms.length < 11) { errs++; console.log(w + ': missing forms'); }
    forms.forEach(f => { if (RU.unstressed(f).length) { errs++; console.log(w + ': no stress on ' + f); } });
    if (/[a-z]/i.test(forms.join(''))) { errs++; console.log(w + ': Latin letters in a form'); }
    out.push(v);
  });
});
if (errs) { console.log(errs + ' errors, not written'); process.exit(1); }
fs.writeFileSync(path.join(ROOT, 'russkiy', 'data', 'verbs.js'),
  '/* Svobodno verbs: generated by tools/ru/build-verbs.js from tools/ru/src/verbs.txt and the\n' +
  ' * OpenRussian.org dictionary (github.com/Badestrand/russian-dictionary, CC BY-SA 4.0). Do not edit. */\n' +
  '(function (root) {\n  var V = ' + JSON.stringify(out) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = V;\n  else root.RU_VERBS = V;\n})(this);\n');
console.log(out.length + ' verbs');
