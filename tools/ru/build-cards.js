#!/usr/bin/env node
/* Svobodno cards (the little pages): tools/ru/src/cards.json into russkiy/data/cards.js.
 * A table written as {verb, tense} is filled from verbs.js, so a card can never disagree
 * with the drills. Russian (ru fields, *marked* text in English, table cells) has its
 * stress written as an apostrophe and is gated for missing stress.
 *   node tools/ru/build-cards.js */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const RU = require(path.join(ROOT, 'russkiy/js/ru-text.js'));
const V = require(path.join(ROOT, 'russkiy/data/verbs.js'));
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'cards.json'), 'utf8'));
const PRON = [['I', 'я'], ['you', 'ты'], ['he, she', 'он, она'], ['we', 'мы'], ['you (polite, plural)', 'вы'], ['they', 'они']];
let errs = 0;
const bad = (k, m) => { errs++; console.log('card ' + k + ': ' + m); };
function ru(k, s) {
  s = RU.fromApostrophe(s);
  const u = RU.unstressed(s.replace(/\B-[а-яё]+/g, ' ').replace(/[A-Za-z][A-Za-z ,.!?()']*/g, ' ')); if (u.length) bad(k, 'no stress on ' + u.join(' '));
  if (/[a-z]/i.test(s.replace(/[A-Za-z ,.!?()']*[A-Za-z]/g, ''))) bad(k, 'Latin inside Russian: ' + s);
  return s;
}
function en(k, s) { return String(s).replace(/\*([^*]+)\*/g, (m, x) => { if (/[a-z]/i.test(x)) bad(k, 'Latin in *' + x + '*'); return '*' + ru(k, x) + '*'; }); }
Object.keys(C).forEach(k => {
  const c = C[k]; c.topic = k;
  c.name.ru = ru(k, c.name.ru);
  c.when = c.when.map(w => ({ en: en(k, w.en) }));
  c.how = { en: en(k, c.how.en) };
  c.tip = { en: en(k, c.tip.en) };
  c.ex = c.ex.map(x => ({ ru: ru(k, x.ru), en: x.en }));
  const t = c.table;
  if (t && t.verb) {
    const v = V.find(x => RU.strip(x.inf) === t.verb);
    if (!v) { bad(k, 'no verb ' + t.verb); return; }
    if (t.tense === 'past') c.table = { head: ['', '', ''], rows: [['a man', 'он', v.past.m], ['a woman', 'она', v.past.f], ['it', 'оно', v.past.n], ['more than one', 'они', v.past.pl]] };
    else { const f = v[t.tense === 'pres' ? 'pres' : 'fut']; if (!f) { bad(k, 'no ' + t.tense); return; } c.table = { head: ['', '', ''], rows: PRON.map((p, i) => [p[0], p[1], f[i]]) }; }
  } else if (t && t.rows) {
    t.rows = t.rows.map(r => r.map(x => /[а-яё]/i.test(x) ? ru(k, x) : x));
  }
  if (/[–—]|\s-\s/.test(JSON.stringify(c))) bad(k, 'dash');
});
if (errs) { console.log(errs + ' errors, not written'); process.exit(1); }
fs.writeFileSync(path.join(ROOT, 'russkiy', 'data', 'cards.js'), '/* Svobodno cards: generated by tools/ru/build-cards.js from tools/ru/src/cards.json. Do not edit. */\n' +
  '(function (root) {\n  var C = ' + JSON.stringify(C) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = C;\n  else root.RU_CARDS = C;\n})(this);\n');
console.log(Object.keys(C).length + ' cards');
