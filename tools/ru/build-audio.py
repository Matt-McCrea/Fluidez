#!/usr/bin/env python3
"""Svobodno audio: a clip for every letter, word, phrase and sentence, from Microsoft's
neural voices (edge-tts), generated at build time and shipped as mp3 files.
Clips are made once into tools/ru/vendor/clips/ (kept, so a rerun only makes the
new ones), then packed about forty to a bundle, russkiy/audio/<kind>-<hash>.bin,
because GitHub Pages times out syncing thousands of small files. Bundles are named
by content, so the app can cache them for good.
  tools/ar/vendor/venv/bin/python tools/ru/build-audio.py
Writes russkiy/audio/*.bin and russkiy/data/audio.js ("text|v": "audio/x.bin#off,len")."""
import asyncio, hashlib, json, os, subprocess, sys
import unicodedata
import edge_tts

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
AUD = os.path.join(HERE, 'vendor', 'clips')
PACK = os.path.join(ROOT, 'russkiy', 'audio')
PER = 40
OUT = os.path.join(ROOT, 'russkiy', 'data', 'audio.js')
VOICES = {'ru': ['ru-RU-SvetlanaNeural', 'ru-RU-DmitryNeural']}  # picked by the text, so a word always has the same voice

def spoken(text):
    """The voice is given the text without the learner's stress marks (it reads them as noise)."""
    return unicodedata.normalize('NFC', unicodedata.normalize('NFD', text).replace('\u0301', ''))

def name_for(item):
    h = hashlib.sha1((item['text'] + '|' + item['v']).encode('utf-8')).hexdigest()[:10]
    return ('l-' if item['kind'] == 'letter' else 'r-') + h + '.mp3'   # l- is precached

async def one(item, sem, fails):
    fn = os.path.join(AUD, name_for(item))
    if os.path.exists(fn) and os.path.getsize(fn) > 1000: return
    vs = VOICES[item['v']]
    voice = vs[int(hashlib.md5(item['text'].encode('utf-8')).hexdigest(), 16) % len(vs)]
    if item['kind'] == 'letter': voice = 'ru-RU-SvetlanaNeural'
    async with sem:
        for attempt in range(4):
            if attempt == 2:  # Dmitry sends no audio for some short texts: the other voice reads them
                voice = vs[1 - vs.index(voice)] if voice in vs else voice
            try:
                c = edge_tts.Communicate(spoken(item['text']), voice, rate='-25%' if item['slow'] else '-5%')
                await c.save(fn)
                if os.path.getsize(fn) > 1000: return
            except Exception as e:  # network hiccup: wait and retry
                await asyncio.sleep(2 + attempt * 3)
        fails.append(item['text'])

def pack(items):
    """Bundle the clips by kind, in list order (letters, then words by rank,
    phrases, sentences), PER to a file. Returns the audio map."""
    os.makedirs(PACK, exist_ok=True)
    groups, m, keep = {}, {}, set()
    for i in items:
        k = 'l' if i['kind'] == 'letter' else {'word': 'w', 'phrase': 'p', 'sentence': 's'}.get(i['kind'], 'x')
        groups.setdefault(k, []).append(i)
    for k, lst in groups.items():
        for n in range(0, len(lst), PER):
            chunk, blob, refs = lst[n:n + PER], bytearray(), []
            for i in chunk:
                data = open(os.path.join(AUD, name_for(i)), 'rb').read()
                refs.append((i, len(blob), len(data)))
                blob += data
            name = k + '-' + hashlib.sha1(bytes(blob)).hexdigest()[:10] + '.bin'
            keep.add(name)
            fn = os.path.join(PACK, name)
            if not os.path.exists(fn): open(fn, 'wb').write(blob)
            for i, off, ln in refs: m[i['text'] + '|' + i['v']] = 'audio/%s#%d,%d' % (name, off, ln)
    for f in os.listdir(PACK):          # bundles nothing points at any more
        if f not in keep: os.remove(os.path.join(PACK, f))
    return m

async def main():
    os.makedirs(AUD, exist_ok=True)
    lines = subprocess.run(['node', os.path.join(HERE, 'audio-list.js')], capture_output=True, text=True, check=True).stdout
    items = [json.loads(l) for l in lines.splitlines() if l.strip()]
    sem, fails = asyncio.Semaphore(2), []
    await asyncio.gather(*(one(i, sem, fails) for i in items))
    m = pack([i for i in items if os.path.exists(os.path.join(AUD, name_for(i))) and os.path.getsize(os.path.join(AUD, name_for(i))) > 1000])
    js = ('/* Svobodno audio map: generated by tools/ru/build-audio.py. Voices: Microsoft neural TTS\n'
          ' * (ru-RU Svetlana and Dmitry). Do not edit. */\n'
          '(function (root) {\n  var A = ' + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n'
          '  if (typeof module !== "undefined" && module.exports) module.exports = A;\n  else root.RU_AUDIO = A;\n})(this);\n')
    open(OUT, 'w', encoding='utf-8').write(js)
    print(len(items), 'texts,', len(m), 'clips,', len(fails), 'failed')
    if fails: print('failed:', ' '.join(fails[:20]), file=sys.stderr)

if __name__ == '__main__':
    asyncio.run(main())
