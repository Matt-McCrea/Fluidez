#!/usr/bin/env node
/* Svobodno phrases: tools/ru/src/phrases.txt into russkiy/data/phrases.js, and
 * tools/ru/src/speak.json into russkiy/data/speak.js, gated.
 *   node tools/ru/build-phrases.js
 * Phrase: { id, en, ru, tr, th, b, n, alt:[] }. Gate: every word of two vowels or
 * more carries its stress, no dashes in the English or the note, ids unique, every
 * speak id a phrase. */
'use strict';
const fs = require('fs');
const path = require('path');
const RU = require('../../russkiy/js/ru-text.js');
const ROOT = path.join(__dirname, '..', '..');
let DROP = [];
try { DROP = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'drop.json'), 'utf8')).phrases || []; } catch (e) {}

let errs = 0;
const bad = (id, m) => { errs++; console.log(id + ': ' + m); };
const out = [], byId = {};
fs.readFileSync(path.join(__dirname, 'src', 'phrases.txt'), 'utf8').split(/\r?\n/).forEach(line => {
  if (!line.trim() || line[0] === '#') return;
  const c = line.split('|').map(s => s.trim());
  const [id, b, th, en, ru0, n, alt] = c;
  if (!id || !b || !th || !en || !ru0) return bad(id || line, 'needs id, band, theme, English, Russian');
  if (DROP.indexOf(id) !== -1) return;
  if (byId[id]) return bad(id, 'duplicate id');
  const ru = RU.fromApostrophe(ru0);
  const un = RU.unstressed(ru); if (un.length) bad(id, 'no stress on ' + un.join(' '));
  if (/'/.test(ru)) bad(id, 'stray apostrophe');
  const note = n ? RU.fromApostrophe(n) : null;
  if (note) { const u2 = RU.unstressed(note.replace(/[A-Za-z][A-Za-z ,.!?]*/g, ' ')); if (u2.length) bad(id, 'note: no stress on ' + u2.join(' ')); }
  if (/[–—]|\s-\s/.test(en + (n || ''))) bad(id, 'dash');
  const p = { id, en, ru, tr: RU.translit(ru), th, b, n: note, alt: alt ? alt.split(';').map(s => RU.fromApostrophe(s.trim())).filter(Boolean) : [] };
  byId[id] = p; out.push(p);
});

const SP = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'speak.json'), 'utf8'));
SP.packs.forEach(k => {
  k.ids.concat(k.dialogue.map(d => d[1])).forEach(id => { if (!byId[id]) bad('speak ' + k.n, id + ' is not a phrase'); });
});
if (errs) { console.log(errs + ' errors, not written'); process.exit(1); }
const packs = SP.packs.map(k => ({ n: k.n, en: k.en, ru: RU.fromApostrophe(k.ru), ids: k.ids, dialogue: k.dialogue.map(d => ({ who: d[0], id: d[1] })) }));
const w = (file, name, data, what) => fs.writeFileSync(path.join(ROOT, 'russkiy', 'data', file),
  '/* Svobodno ' + what + ': generated by tools/ru/build-phrases.js. Do not edit. */\n' +
  '(function (root) {\n  var D = ' + JSON.stringify(data) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = D;\n  else root.' + name + ' = D;\n})(this);\n');
w('phrases.js', 'RU_PHRASES', out, 'phrases (written by hand)');
w('speak.js', 'RU_SPEAK', packs, 'speak first (tools/ru/src/speak.json)');
console.log(out.length + ' phrases, ' + packs.length + ' packs');
