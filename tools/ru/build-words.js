#!/usr/bin/env node
/* Svobodno words: OpenRussian (tools/ru/vendor/*.csv, CC BY-SA 4.0) into russkiy/data/words.js
 * and russkiy/data/nouns.js (the case tables), gated.
 *   node tools/ru/build-words.js --cands   writes tools/ru/judge/word-cands.json for the judges
 *   node tools/ru/build-words.js           builds, using tools/ru/src/word-fix.json
 * Order: each file is in OpenRussian's frequency order; the four are merged in
 * proportion (nouns half, adjectives and verbs a fifth each, small words a tenth),
 * then the judges' tier (1 everyday, 2 common, 3 bookish) ranks first, as in Ṭalāqa.
 * A spelling that is also a verb or a small word is dropped as a noun or adjective
 * (стать is not "figure" for a learner). word-fix.json: { word: {en, tier, th, drop, b} }. */
'use strict';
const fs = require('fs');
const path = require('path');
const RU = require('../../russkiy/js/ru-text.js');
const ROOT = path.join(__dirname, '..', '..');
const V = path.join(__dirname, 'vendor');

function tsv(f) {
  const lines = fs.readFileSync(path.join(V, f), 'utf8').split(/\r?\n/).filter(Boolean);
  const head = lines[0].split('\t');
  return lines.slice(1).map((l, i) => { const c = l.split('\t'), o = { i }; head.forEach((h, k) => { o[h] = (c[k] || '').trim(); }); return o; });
}
function S(s) {
  s = RU.fromApostrophe(String(s || '').split(/[,;]/)[0].trim());
  const bare = s.replace(/́/g, '');
  if ((bare.match(/[аеёиоуыэюя]/gi) || []).length < 2 || /ё/i.test(bare)) return bare;
  return s;
}
function gloss(t) {
  return String(t || '').split(';')[0].split(',').slice(0, 2).map(x => x.trim()).filter(Boolean).join(', ');
}
const files = { n: ['nouns.csv', 0.5], a: ['adjectives.csv', 0.2], v: ['verbs.csv', 0.2], o: ['others.csv', 0.1] };
const T = {}; Object.keys(files).forEach(k => { T[k] = tsv(files[k][0]); });
const verbOrSmall = new Set(T.v.map(r => r.bare).concat(T.o.map(r => r.bare)));
const smallSet = new Set(T.o.map(r => r.bare));
const seen = new Set();
let cands = [];
['o', 'v', 'a', 'n'].forEach(k => {
  T[k].forEach(r => {
    const w = r.bare;
    if (!w || !/^[а-яё\- ]+$/.test(w)) return;                // lower case Cyrillic only: no names
    if ((k === 'n' || k === 'a') && verbOrSmall.has(w)) return;
    if (k === 'v' && smallSet.has(w)) return;
    if (seen.has(w)) return;
    if (!r.translations_en) return;
    seen.add(w);
    cands.push({ w, k, r, score: r.i / files[k][1] });
  });
});
cands.sort((a, b) => a.score - b.score);
cands = cands.slice(0, 3200);

if (process.argv.includes('--cands')) {
  fs.mkdirSync(path.join(__dirname, 'judge'), { recursive: true });
  const rows = cands.map((c, i) => ({ i, w: c.w, pos: c.k, en: c.r.translations_en.slice(0, 80) }));
  fs.writeFileSync(path.join(__dirname, 'judge', 'word-cands.json'), JSON.stringify(rows));
  console.log(rows.length + ' candidates in tools/ru/judge/word-cands.json');
  process.exit(0);
}

let FIX = {};
try { FIX = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'word-fix.json'), 'utf8')); } catch (e) {}
const TIER = { 1: 20, 2: 10, 3: 0 };
let errs = 0;
const words = [], nouns = {};
cands.forEach((c, i) => {
  const f = FIX[c.w] || {};
  if (f.drop) return;
  const r = c.r;
  const e = { ru: S(f.ru || r.accented), en: f.en || gloss(r.translations_en), pos: c.k, th: f.th || '', t: f.tier || 2, i };
  if (c.k === 'n') {
    e.g = r.pl_only === '1' ? 'pl' : (r.gender || '');
    const cs = ['nom', 'gen', 'dat', 'acc', 'inst', 'prep'];
    const sg = cs.map(x => S(r['sg_' + x])), pl = cs.map(x => S(r['pl_' + x]));
    nouns[c.w] = { g: e.g, an: r.animate === '1', ind: r.indeclinable === '1', sg, pl };
    if (r.indeclinable === '1') e.ind = 1;
  }
  if (RU.unstressed(e.ru).length) { errs++; console.log('no stress: ' + e.ru); }
  if (/[–—]|\s-\s/.test(e.en)) { errs++; console.log('dash in gloss: ' + c.w); }
  words.push(e);
});
words.sort((a, b) => (TIER[b.t] - TIER[a.t]) || (a.i - b.i));
const BANDS = [[700, 'A1'], [1400, 'A2'], [2100, 'B1'], [1e9, 'B2']];
words.forEach((e, k) => { e.r = k; e.b = (FIX[e.ru] && FIX[e.ru].b) || BANDS.find(x => k < x[0])[1]; delete e.i; delete e.t; });
if (errs) { console.log(errs + ' errors, not written'); process.exit(1); }
const head = '/* Svobodno: generated by tools/ru/build-words.js from the OpenRussian.org dictionary\n' +
  ' * (github.com/Badestrand/russian-dictionary, CC BY-SA 4.0) and tools/ru/src/word-fix.json. Do not edit. */\n';
fs.writeFileSync(path.join(ROOT, 'russkiy', 'data', 'words.js'), head +
  '(function (root) {\n  var W = ' + JSON.stringify(words) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = W;\n  else root.RU_WORDS = W;\n})(this);\n');
fs.writeFileSync(path.join(ROOT, 'russkiy', 'data', 'nouns.js'), head +
  '(function (root) {\n  var N = ' + JSON.stringify(nouns) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = N;\n  else root.RU_NOUNS = N;\n})(this);\n');
console.log(words.length + ' words, ' + Object.keys(nouns).length + ' noun tables');
