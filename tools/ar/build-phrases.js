#!/usr/bin/env node
/* Ṭalāqa phrases: tools/ar/src/phrases.json into arabiya/data/phrases.js, gated.
 *   node tools/ar/build-phrases.js */
'use strict';
const fs = require('fs');
const path = require('path');
const AR = require('../../arabiya/js/ar-text.js');
const ROOT = path.join(__dirname, '..', '..');
const P = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'phrases.json'), 'utf8'));
const DROP = (() => { try { return JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'drop.json'), 'utf8')).phrases || []; } catch (e) { return []; } })();
const ids = new Set(); let errs = 0;
const out = P.filter(p => DROP.indexOf(p.id) === -1).filter(p => {
  const bad = m => { errs++; console.log(`${p.id}: ${m}`); return false; };
  if (!p.id || !p.en || !p.msa || !p.th || !p.b) return bad('needs id, en, msa, th, b');
  if (ids.has(p.id)) return bad('duplicate id'); ids.add(p.id);
  const u = AR.unvowelled(p.msa); if (u.length) return bad('msa not fully vowelled: ' + u.join(' '));
  if (/[–—]|\s-\s/.test(p.en + (p.n || ''))) return bad('dash');
  p.alt = p.alt || {}; p.lev = p.lev || ''; p.egy = p.egy || '';
  return true;
});
/* Speak first (src/speak.json): the packs, and a hand-written transliteration per
 * variety on every phrase a pack uses. Gate: each id exists, each has all three. */
const SP = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'speak.json'), 'utf8'));
const byId = {}; out.forEach(p => { byId[p.id] = p; });
const need = new Set();
SP.packs.forEach(k => { k.ids.forEach(i => need.add(i)); k.dialogue.forEach(d => need.add(d[1])); });
need.forEach(id => {
  const p = byId[id], t = SP.tr[id];
  if (!p) { errs++; console.log(`speak: ${id} is not a phrase`); return; }
  if (!t || !t.msa || !t.lev || !t.egy) { errs++; console.log(`speak: ${id} needs tr for msa, lev and egy`); return; }
  if (/[–—]|\s-\s/.test(t.msa + t.lev + t.egy)) { errs++; console.log(`speak: ${id} dash in tr`); return; }
  p.tr = t;
});
Object.keys(SP.tr).forEach(id => { if (byId[id] && !byId[id].tr) byId[id].tr = SP.tr[id]; });
if (errs) { console.log('not written: fix the errors above'); process.exit(1); }
const packs = SP.packs.map(k => ({ n: k.n, en: k.en, ar: k.ar, ids: k.ids, dialogue: k.dialogue.map(d => ({ who: d[0], id: d[1] })) }));
fs.writeFileSync(path.join(ROOT, 'arabiya', 'data', 'speak.js'), '/* Ṭalāqa speak first: generated by tools/ar/build-phrases.js from tools/ar/src/speak.json. Do not edit. */\n' +
  '(function (root) {\n  var S = ' + JSON.stringify(packs) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = S;\n  else root.AR_SPEAK = S;\n})(this);\n');
fs.writeFileSync(path.join(ROOT, 'arabiya', 'data', 'phrases.js'), '/* Ṭalāqa phrases: generated by tools/ar/build-phrases.js from tools/ar/src/phrases.json. Do not edit. */\n' +
  '(function (root) {\n  var P = ' + JSON.stringify(out) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = P;\n  else root.AR_PHRASES = P;\n})(this);\n');
console.log(out.length + ' phrases' + (errs ? `, ${errs} dropped for errors` : ''));
