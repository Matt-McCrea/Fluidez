#!/usr/bin/env node
/* Ṭalāqa cards (the little pages): tools/ar/src/cards.json into arabiya/data/cards.js.
 * A table written as {verb, tense, persons?, prefix?} is filled from verbs.js, so a
 * card can never disagree with the drills.   node tools/ar/build-cards.js */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const V = require(path.join(ROOT, 'arabiya', 'data', 'verbs.js'));
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'cards.json'), 'utf8'));
const PRON = { ana: ['I', 'أَنَا'], anta: ['you (m)', 'أَنْتَ'], anti: ['you (f)', 'أَنْتِ'], huwa: ['he', 'هُوَ'], hiya: ['she', 'هِيَ'], nahnu: ['we', 'نَحْنُ'], antum: ['you (pl)', 'أَنْتُمْ'], hum: ['they', 'هُمْ'], antunna: ['you (f pl)', 'أَنْتُنَّ'], hunna: ['they (f)', 'هُنَّ'] };
const ORDER = ['ana', 'anta', 'anti', 'huwa', 'hiya', 'nahnu', 'antum', 'hum', 'antunna', 'hunna'];
let errs = 0;
Object.keys(C).forEach(k => {
  const c = C[k]; c.topic = k;
  const t = c.table;
  if (t && t.verb) {
    const v = V.find(x => x.v === t.verb);
    const f = v && v.f[t.tense];
    if (!f) { console.log(`card ${k}: no ${t.tense} for ${t.verb}`); errs++; return; }
    const ps = (t.persons || ORDER).filter(p => f[p]);
    c.table = { head: ['', '', ''], rows: ps.map(p => [PRON[p][0], PRON[p][1], (t.prefix ? t.prefix + ' ' : '') + f[p]]) };
  }
  if (/[–—]/.test(JSON.stringify(c))) { console.log(`card ${k}: dash`); errs++; }
});
fs.writeFileSync(path.join(ROOT, 'arabiya', 'data', 'cards.js'), '/* Ṭalāqa cards: generated by tools/ar/build-cards.js from tools/ar/src/cards.json. Do not edit. */\n' +
  '(function (root) {\n  var C = ' + JSON.stringify(C) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = C;\n  else root.AR_CARDS = C;\n})(this);\n');
console.log(Object.keys(C).length + ' cards' + (errs ? `, ${errs} errors` : ''));
process.exitCode = errs ? 1 : 0;
