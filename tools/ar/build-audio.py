#!/usr/bin/env python3
"""Ṭalāqa audio: a clip for every letter, word and phrase, from Microsoft's
neural voices (edge-tts), generated at build time and shipped as mp3 files.
Existing clips are kept, so a rerun only makes the new ones.
  tools/ar/vendor/venv/bin/python tools/ar/build-audio.py
Writes arabiya/audio/*.mp3 and arabiya/data/audio.js."""
import asyncio, hashlib, json, os, subprocess, sys
import edge_tts

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
AUD = os.path.join(ROOT, 'arabiya', 'audio')
OUT = os.path.join(ROOT, 'arabiya', 'data', 'audio.js')
VOICES = {  # two voices per variety, picked by the text so a word always has the same voice
    'msa': ['ar-SA-HamedNeural', 'ar-SA-ZariyahNeural'],
    'lev': ['ar-LB-RamiNeural', 'ar-LB-LaylaNeural', 'ar-JO-TaimNeural', 'ar-JO-SanaNeural'],
    'egy': ['ar-EG-ShakirNeural', 'ar-EG-SalmaNeural'],
}

def name_for(item):
    h = hashlib.sha1((item['text'] + '|' + item['v']).encode('utf-8')).hexdigest()[:10]
    return ('l-' if item['kind'] == 'letter' else {'msa': 'm', 'lev': 's', 'egy': 'e'}[item['v']] + '-') + h + '.mp3'   # l- is precached

async def one(item, sem, fails):
    fn = os.path.join(AUD, name_for(item))
    if os.path.exists(fn) and os.path.getsize(fn) > 1000: return
    vs = VOICES[item['v']]
    voice = vs[int(hashlib.md5(item['text'].encode('utf-8')).hexdigest(), 16) % len(vs)]
    if item['kind'] == 'letter': voice = 'ar-SA-HamedNeural'
    async with sem:
        for attempt in range(3):
            try:
                c = edge_tts.Communicate(item['text'], voice, rate='-25%' if item['slow'] else '-5%')
                await c.save(fn)
                if os.path.getsize(fn) > 1000: return
            except Exception as e:  # network hiccup: wait and retry
                await asyncio.sleep(2 + attempt * 3)
        fails.append(item['text'])

async def main():
    os.makedirs(AUD, exist_ok=True)
    lines = subprocess.run(['node', os.path.join(HERE, 'audio-list.js')], capture_output=True, text=True, check=True).stdout
    items = [json.loads(l) for l in lines.splitlines() if l.strip()]
    sem, fails = asyncio.Semaphore(4), []
    await asyncio.gather(*(one(i, sem, fails) for i in items))
    m = {i['text'] + '|' + i['v']: 'audio/' + name_for(i) for i in items if os.path.exists(os.path.join(AUD, name_for(i)))}
    js = ('/* Ṭalāqa audio map: generated by tools/ar/build-audio.py. Voices: Microsoft neural TTS\n'
          ' * (ar-SA for fuṣḥā, ar-LB and ar-JO for shāmī, ar-EG for maṣrī). Do not edit. */\n'
          '(function (root) {\n  var A = ' + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n'
          '  if (typeof module !== "undefined" && module.exports) module.exports = A;\n  else root.AR_AUDIO = A;\n})(this);\n')
    open(OUT, 'w', encoding='utf-8').write(js)
    print(len(items), 'texts,', len(m), 'clips,', len(fails), 'failed')
    if fails: print('failed:', ' '.join(fails[:20]), file=sys.stderr)

if __name__ == '__main__':
    asyncio.run(main())
