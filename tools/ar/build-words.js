#!/usr/bin/env node
/* Ṭalāqa words: tools/ar/src/words/*.json plus the verbs, ranked by the CAMeL
 * MSA frequency list (CC BY-SA 4.0, Inoue et al. 2021), into arabiya/data/words.js.
 *   node tools/ar/build-words.js
 * Rank: the bare form's count, plus its count with the article and the common
 * one-letter prefixes, nudged by the authored tier (t 1 words first). Bands by
 * rank: A1 the first 650 (about the tier 1 words), A2 to 1300, B1 to 2000, B2 after. */
'use strict';
const fs = require('fs');
const path = require('path');
const AR = require('../../arabiya/js/ar-text.js');
const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(__dirname, 'src', 'words');
const FREQ = path.join(__dirname, 'vendor', 'freq-top200k.tsv');
const OUT = path.join(ROOT, 'arabiya', 'data', 'words.js');
const DROP = (() => { try { return JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'drop.json'), 'utf8')).words || []; } catch (e) { return []; } })();

const freq = new Map();
if (fs.existsSync(FREQ)) fs.readFileSync(FREQ, 'utf8').split('\n').forEach(l => {
  const i = l.indexOf('\t'); if (i > 0) freq.set(l.slice(0, i), +l.slice(i + 1));
});
const f = s => freq.get(s) || 0;
function count(ar) {
  const b = AR.strip(ar);
  if (b.indexOf(' ') !== -1) return Math.min.apply(null, b.split(' ').map(x => f(x) + f('ال' + x)));
  const bt = b.replace(/ة$/, 'ت');
  return f(b) + f('ال' + b) + f('و' + b) + f('ب' + b) + f('ل' + b) + f('وال' + b) + f('بال' + b) + (bt !== b ? f(bt) : 0);
}

const words = [];
fs.readdirSync(SRC).filter(x => x.endsWith('.json')).sort().forEach(file => {
  JSON.parse(fs.readFileSync(path.join(SRC, file), 'utf8')).forEach(w => words.push(Object.assign({}, w)));
});
const V = require(path.join(ROOT, 'arabiya', 'data', 'verbs.js'));
V.forEach(v => words.push({ ar: v.v, en: v.en, pos: 'v', th: 'verbs', t: { A1: 1, A2: 2, B1: 3, B2: 3 }[v.b], root: '', ms: v.ms }));

// drop authored duplicates (same bare form and same gloss) and dropped items
const seen = new Set(), out = [];
words.forEach(w => {
  const k = AR.strip(w.ar) + '|' + w.en.toLowerCase();
  if (seen.has(k) || DROP.indexOf(w.ar) !== -1) return;
  seen.add(k); out.push(w);
});

// rank: frequency, with the tier as a strong prior
const TIER = { 1: 40, 2: 4, 3: 1 };
out.forEach(w => { w._s = Math.log10(1 + count(w.ar)) + { 1: 20, 2: 10, 3: 0 }[w.t]; });   // tier first, frequency within
out.sort((a, b) => b._s - a._s);
out.forEach((w, i) => { w.r = i + 1; w.b = i < 650 ? 'A1' : i < 1300 ? 'A2' : i < 2000 ? 'B1' : 'B2'; delete w._s; delete w.t; });

// homographs: words that look the same without vowels keep their vowels at the help level
const byBare = new Map();
out.forEach(w => { const b = AR.strip(w.ar); byBare.set(b, (byBare.get(b) || []).concat(w)); });
byBare.forEach(list => { if (list.length > 1 && new Set(list.map(w => w.ar)).size > 1) list.forEach(w => { w.h = w.ar; }); });

const head = '/* Ṭalāqa words: generated by tools/ar/build-words.js from tools/ar/src/words/*.json and verbs.\n' +
  ' * Order from the CAMeL MSA frequency lists (CC BY-SA 4.0). Do not edit. */\n';
fs.writeFileSync(OUT, head + '(function (root) {\n  var W = ' + JSON.stringify(out) + ';\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = W;\n  else root.AR_WORDS = W;\n})(this);\n');
const bands = {}; out.forEach(w => { bands[w.b] = (bands[w.b] || 0) + 1; });
console.log(out.length, 'words', JSON.stringify(bands), '->', path.relative(ROOT, OUT));
