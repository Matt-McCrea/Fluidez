#!/usr/bin/env python3
"""Ṭalāqa verbs: conjugate tools/ar/src/verbs.json with Qutrub (GPL, run at
build time only; only its output is shipped) into arabiya/data/verbs.js.
  tools/ar/vendor/venv/bin/python tools/ar/build-verbs.py
"""
import json, os, re, sys
from libqutrub import conjugator

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'src', 'verbs.json')
OUT = os.path.join(ROOT, 'arabiya', 'data', 'verbs.js')

PV = {'a': 'فتحة', 'i': 'كسرة', 'u': 'ضمة', '': 'فتحة'}
TENSES = {
    'madi': 'الماضي المعلوم', 'mudari': 'المضارع المعلوم', 'mansub': 'المضارع المنصوب',
    'majzum': 'المضارع المجزوم', 'amr': 'الأمر', 'madi_m': 'الماضي المجهول', 'mudari_m': 'المضارع المجهول',
}
PERSONS = {
    'ana': 'أنا', 'anta': 'أنت', 'anti': 'أنتِ', 'huwa': 'هو', 'hiya': 'هي', 'nahnu': 'نحن',
    'antum': 'أنتم', 'antunna': 'أنتن', 'hum': 'هم', 'hunna': 'هن',
    'antuma': 'أنتما', 'huma': 'هما', 'humaf': 'هما مؤ',
}
# Forms Qutrub gives that a learner should not meet, or where common usage differs.
OVERRIDES = {
    # the short imperatives everyone uses
    ('أَخَذَ', 'amr'): {'anta': 'خُذْ', 'anti': 'خُذِي', 'antum': 'خُذُوا', 'antunna': 'خُذْنَ', 'antuma': 'خُذَا'},
    ('أَكَلَ', 'amr'): {'anta': 'كُلْ', 'anti': 'كُلِي', 'antum': 'كُلُوا', 'antunna': 'كُلْنَ', 'antuma': 'كُلَا'},
    ('سَأَلَ', 'amr'): {'anta': 'اِسْأَلْ', 'anti': 'اِسْأَلِي', 'antum': 'اِسْأَلُوا', 'antunna': 'اِسْأَلْنَ', 'antuma': 'اِسْأَلَا'},
}
NO_AMR = {'كَانَ', 'رَأَى', 'اِسْتَطَاعَ', 'مَاتَ', 'حَدَثَ', 'أَصْبَحَ', 'صَارَ', 'ظَهَرَ', 'سَقَطَ', 'اِحْتَاجَ', 'بَقِيَ', 'وَجَدَ', 'أَدْرَكَ'}
NO_PASSIVE_TENSE = {'كَانَ', 'مَاتَ', 'نَامَ', 'جَاءَ', 'ذَهَبَ', 'خَرَجَ', 'دَخَلَ', 'جَلَسَ', 'رَجَعَ', 'عَادَ', 'وَصَلَ',
                    'مَشَى', 'عَاشَ', 'قَامَ', 'نَزَلَ', 'صَعِدَ', 'ضَحِكَ', 'بَكَى', 'اِسْتَيْقَظَ', 'حَدَثَ', 'بَقِيَ',
                    'أَصْبَحَ', 'صَارَ', 'خَافَ', 'سَقَطَ', 'ظَهَرَ', 'تَوَقَّفَ', 'اِنْتَقَلَ', 'تَغَيَّرَ', 'فَازَ',
                    'رَكَضَ', 'سَبَحَ', 'رَقَصَ', 'سَافَرَ', 'تَكَلَّمَ', 'اِسْتَمَرَّ', 'اِنْتَشَرَ', 'تَطَوَّرَ', 'تَخَرَّجَ',
                    'اِعْتَذَرَ', 'اِحْتَفَلَ', 'اِهْتَمَّ', 'اِسْتَطَاعَ'}

MARKS = re.compile('[ً-ٰٟ]')
def bare(s): return MARKS.sub('', s)

def form_of(v, pv):
    b = bare(v)
    if pv: return 1
    if b.startswith('است'): return 10
    if b.startswith('ان'): return 7
    if b.startswith('ا') and len(b) >= 5 and b[2] in 'تط' or b.startswith('اتّ') or b.startswith('ات'): return 8
    if b.startswith('ت') and 'ّ' in v: return 5
    if b.startswith('ت') and len(b) >= 4 and b[2] == 'ا': return 6
    if b.startswith('أ'): return 4
    if len(b) >= 3 and b[1] == 'ا': return 3
    if 'ّ' in v: return 2
    return 1

def main():
    rows = json.load(open(SRC, encoding='utf-8'))
    band, out, rank = 'A1', [], 0
    for row in rows:
        if len(row) == 1: band = row[0]; continue
        v, pv, en, ms = row
        rank += 1
        r = conjugator.conjugate(v, PV[pv], True, True, True, True, True, True, False, True, display_format='DICT')
        if not r:
            print('NO CONJUGATION', v, file=sys.stderr); sys.exit(1)
        f = {}
        for key, q in TENSES.items():
            if key == 'amr' and v in NO_AMR: continue
            if key.endswith('_m') and v in NO_PASSIVE_TENSE: continue
            d = r.get(q, {})
            t = {}
            for p, qp in PERSONS.items():
                form = (d.get(qp) or '').strip()
                if form: t[p] = form
            t.update(OVERRIDES.get((v, key), {}))
            if v == 'تَوَقَّعَ' and key == 'madi_m':   # Qutrub drops the wāw: تُقِّعَ for تُوُقِّعَ
                t = {p: ('تُوُ' + x[2:]) if x.startswith('تُق') else x for p, x in t.items()}
            if t: f[key] = t
        out.append({'v': v, 'en': en, 'ms': ms, 'form': form_of(v, pv), 'pv': pv or None, 'b': band, 'r': rank, 'f': f})
    head = ('/* Ṭalāqa verbs: generated by tools/ar/build-verbs.py from tools/ar/src/verbs.json.\n'
            ' * Conjugations by Qutrub (Taha Zerrouki, GPL), used at build time only. Do not edit. */\n')
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    js = head + '(function (root) {\n  var V = ' + body + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = V;\n  else root.AR_VERBS = V;\n})(this);\n'
    open(OUT, 'w', encoding='utf-8').write(js)
    print(len(out), 'verbs ->', os.path.relpath(OUT, ROOT))

if __name__ == '__main__':
    main()
