// Brings the rebuild's sentence bank (app/content/bank) into the original app's data/bank/<band>.js,
// re-tagged with the lib tagger and placed by the old spine.   Run: nice npx tsx tools/bank-import.ts
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import vm from 'node:vm';
import { castNames, loadGraph, tagOptions, type GraphNode } from '../lib/graph';
import { tagRow } from '../lib/tagger/tagAll';
import { dialectLint } from '../lib/tagger/dialect';
import { bandOf, dropReason, legalDay, taughtDays, type DropReason } from './bank/lib';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const t0 = Date.now();
const rd = (p: string) => readFileSync(join(ROOT, p), 'utf8');

/* graph + tagger options (as tools/tag-data.ts) */
const gdir = join(ROOT, 'app/content/graph');
const raw: GraphNode[][] = readdirSync(gdir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort().map((f) => JSON.parse(readFileSync(join(gdir, f), 'utf8')));
const graph = loadGraph(raw);
const udir = join(ROOT, 'app/content/units');
const arcs = readdirSync(udir).filter((f) => /^u\d+\.json$/.test(f)).sort().map((f) => (JSON.parse(readFileSync(join(udir, f), 'utf8')).storyArc as string) ?? '').join(' ');
const opts = tagOptions(graph, { names: castNames(arcs) });

/* old spine, read fresh */
const ctx: any = { window: {} };
vm.createContext(ctx);
vm.runInContext(rd('data/course.js'), ctx, { filename: 'data/course.js' });
vm.runInContext(rd('data/lesson-nodes.js'), ctx, { filename: 'data/lesson-nodes.js' });
const days: Array<{ lesson?: string }> = ctx.window.COURSE_DAYS;
const bands: Record<string, number> = ctx.window.COURSE_BANDS;
const taught = taughtDays(graph, days, ctx.window.LESSON_NODES);

/* stream the bank */
const bdir = join(ROOT, 'app/content/bank');
const files = readdirSync(bdir).filter((f) => f.endsWith('.json')).sort();
const seen = new Set<string>();
const dropFirst: Record<string, number> = {};
const dropAny: Record<string, number> = {};
const kept: Record<string, string[]> = { A1: [], A2: [], B1: [], B2: [], C1: [], unplaced: [] };
const keptDays: Array<{ t: string[]; d: number | null }> = [];
let total = 0, same = 0, differ = 0, nHigh = 0, nKept = 0;
const diffs = new Map<string, number>();
const bandKept: Record<string, number> = {};
const neverTaughtReq = new Map<string, number>();

for (const f of files) {
  const rows: any[] = JSON.parse(readFileSync(join(bdir, f), 'utf8'));
  for (const r of rows) {
    total++;
    const tg = tagRow({ id: r.id, es: r.es, targets: r.targets }, opts);
    const a = new Set<string>(r.requires), b = new Set(tg.requires);
    let eq = a.size === b.size;
    for (const n of b) if (!a.has(n)) { eq = false; diffs.set('+' + n, (diffs.get('+' + n) ?? 0) + 1); }
    for (const n of a) if (!b.has(n)) { eq = false; diffs.set('-' + n, (diffs.get('-' + n) ?? 0) + 1); }
    if (eq) same++; else differ++;
    if (tg.confidence === 'high') nHigh++;

    const rules = dialectLint(r.es).filter((x) => x.severity === 'error').map((x) => x.rule);
    const { reason, all } = dropReason(r, tg, rules, seen);
    for (const x of all) dropAny[x] = (dropAny[x] ?? 0) + 1;
    if (reason) { dropFirst[reason] = (dropFirst[reason] ?? 0) + 1; continue; }

    const d = legalDay(graph, taught, tg.requires, days.length);
    for (const n of tg.requires) { const k = graph.nodes.get(n); if (k && k.kind !== 'lexeme' && !taught.has(n)) neverTaughtReq.set(n, (neverTaughtReq.get(n) ?? 0) + 1); }
    const band = d === null ? 'unplaced' : bandOf(d, bands);
    const focus = tg.focus ? tg.focus.span : r.focus ?? null;
    const row = { id: r.id, es: r.es, en: r.en, a: r.accept ?? [], r: tg.requires, t: r.targets ?? [], f: focus, k: r.kind, th: r.theme, d };
    (kept[band] ?? (kept[band] = [])).push(JSON.stringify(row));
    bandKept[band] = (bandKept[band] ?? 0) + 1;
    keptDays.push({ t: r.targets ?? [], d });
    nKept++;
  }
}

/* write */
mkdirSync(join(ROOT, 'data/bank'), { recursive: true });
const sizes: Record<string, number> = {};
for (const band of ['A1', 'A2', 'B1', 'B2', 'C1', 'unplaced']) {
  const name = band === 'unplaced' ? 'UNPLACED' : band;
  const txt = `/* GENERATED by tools/bank-import.ts. Do not edit. Sentence bank rows, re-tagged, d = first legal course day. */\nwindow.BANK_${name} = [\n${(kept[band] ?? []).join(',\n')}\n];\n`;
  writeFileSync(join(ROOT, `data/bank/${band === 'unplaced' ? 'unplaced' : band}.js`), txt);
  sizes[band] = Buffer.byteLength(txt);
}

/* supply */
const byNode = new Map<string, number[]>();
for (const k of keptDays) if (k.d !== null) for (const t of k.t) { let l = byNode.get(t); if (!l) byNode.set(t, l = []); l.push(k.d); }
const short: Array<{ id: string; day: number; n: number; band: string }> = [];
const supplyBand: Record<string, { nodes: number; short: number; rows: number }> = {};
let nTaught = 0;
for (const [id, day] of [...taught].sort((x, y) => x[1] - y[1])) {
  const k = graph.nodes.get(id)?.kind;
  if (!k || !['grammar', 'pattern', 'chunk', 'contrast'].includes(k)) continue;
  nTaught++;
  const n = (byNode.get(id) ?? []).filter((d) => d <= day + 14).length;
  const band = bandOf(day, bands);
  const s = supplyBand[band] ?? (supplyBand[band] = { nodes: 0, short: 0, rows: 0 });
  s.nodes++; s.rows += n;
  if (n < 8) { s.short++; short.push({ id, day, n, band }); }
}
const top = (m: Map<string, number>, n: number) => [...m].sort((x, y) => y[1] - x[1]).slice(0, n);
const pct = (x: number, y: number) => (y ? (100 * x / y).toFixed(1) : '0') + '%';
const md = `# Bank supply against the old course

Generated by tools/bank-import.ts. The rebuild's bank (${files.length} files, ${total} rows) re-tagged with the lib tagger, cleaned, and placed by the old spine (COURSE_DAYS + LESSON_NODES teaches).

## Rows

- Read: ${total}. Kept: ${nKept}. Dropped: ${total - nKept}.
- Dropped, by first reason: ${Object.entries(dropFirst).map(([k, v]) => `${k} ${v}`).join(', ')}.
- Rows meeting each rule (overlapping): ${Object.entries(dropAny).map(([k, v]) => `${k} ${v}`).join(', ')}.
- Kept per band (band of the legal day): ${['A1', 'A2', 'B1', 'B2', 'C1', 'unplaced'].map((b) => `${b} ${bandKept[b] ?? 0}`).join(', ')}.
- Unplaced (no legal day): ${bandKept.unplaced ?? 0}. The rule lets lexemes, unknown ids and never-taught nodes through, so a row has no legal day only if the spine is empty.
- Kept rows that require a graph node the old spine never teaches (not blocking, but a sign the spine does not cover them): top ${top(neverTaughtReq, 15).map(([k, v]) => `${k} ${v}`).join(', ')}.

## Supply per band

Taught grammar, pattern, chunk and contrast nodes: ${nTaught}. Supply = kept rows targeting the node with legalDay <= taught day + 14.

| Band | Taught nodes | Short (<8 rows) | Rows counted (sum over nodes) |
|---|---|---|---|
${Object.entries(supplyBand).map(([b, s]) => `| ${b} | ${s.nodes} | ${s.short} | ${s.rows} |`).join('\n')}

## Nodes short of supply (need a top-up): ${short.length}

| Node | Taught day | Band | Rows |
|---|---|---|---|
${short.map((s) => `| ${s.id} | ${s.day} | ${s.band} | ${s.n} |`).join('\n')}

## Re-tag against stored requires

- Identical requires sets: ${same} of ${total} (${pct(same, total)}). Differ: ${differ}.
- Re-tag confidence high: ${nHigh} (${pct(nHigh, total)}).
- 20 most common differences ('+' the lib tagger adds, '-' the stored set had it and the lib tagger does not):

${top(diffs, 20).map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`;
writeFileSync(join(ROOT, 'docs/plan-2026-11-04/bank-supply.md'), md);
console.log(JSON.stringify({ secs: (Date.now() - t0) / 1000, total, nKept, dropFirst, dropAny, bandKept, sizes, short: short.length, same, differ, nHigh, rssMB: Math.round(process.memoryUsage().rss / 1e6), nTaught }, null, 1));
