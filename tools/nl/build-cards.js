#!/usr/bin/env node
/* build-cards.js: nederlands/data/cards.js (window.NL_CARDS, the little pages)
 * from tools/nl/src/cards.json. Shape: docs/vlot-spec.md. Fails on a dash in
 * any text or a card missing a part. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const cards = JSON.parse(fs.readFileSync(path.join(__dirname, 'src', 'cards.json'), 'utf8'));
const KEYS = 'ott ovt vtt hz toek cond imp kofschip scheid modaal wederkerend dehet adj volgorde bijzin te geen mv dim pron er getallen'.split(' ');
const TENSES = KEYS.slice(0, 7);
const bad = [];
KEYS.forEach(k => { if (!cards[k]) bad.push(k + ': missing'); });
Object.keys(cards).forEach(k => {
  const c = cards[k];
  if (KEYS.indexOf(k) < 0) bad.push(k + ': unknown key');
  if (c.kind !== (TENSES.indexOf(k) >= 0 ? 'tense' : 'grammar')) bad.push(k + ': wrong kind');
  ['topic', 'name', 'when', 'how', 'table', 'ex', 'tip'].forEach(f => { if (!c[f]) bad.push(k + ': no ' + f); });
  JSON.stringify(c).replace(/[–—]|\s-\s/g, m => { bad.push(k + ': dash'); return m; });
  [c.name, c.how, c.tip].concat(c.when || []).forEach(x => { if (x && (!x.nl || !x.en)) bad.push(k + ': text needs nl and en'); });
  if (!c.when || c.when.length < 2 || c.when.length > 4) bad.push(k + ': when needs 2 to 4');
  if (!c.ex || c.ex.length !== 3) bad.push(k + ': needs three examples');
  (c.ex || []).forEach(e => { if (!e.nl || !e.en) bad.push(k + ': example needs nl and en'); });
  const t = c.table || {};
  (t.rows || []).forEach((r, i) => { if (!t.head || r.length !== t.head.length) bad.push(k + ': table row ' + i + ' width'); });
});
/* A card's `irr` ({tense, verbs}) becomes tabs of full tables at its foot, one
 * per strong or irregular verb, built from verbs.js so the tabs match the drills. */
const VERBS = require(path.join(ROOT, 'nederlands', 'data', 'verbs.js'));
const PERS = [['ik', 'ik', 'sg'], ['jij', 'jij', 'sg'], ['hij / zij', 'hij', 'sg'], ['wij', 'wij', 'pl'], ['jullie', 'jullie', 'pl'], ['zij', 'zij', 'pl']];
const AUX = { h: { ik: 'heb', jij: 'hebt', hij: 'heeft', pl: 'hebben' }, z: { ik: 'ben', jij: 'bent', hij: 'is', pl: 'zijn' } };
function irrTable(v, t) {
  if (t === 'ovt') return { head: ['', ''], rows: PERS.map(([l, p, n]) => [l, v.f.ovt[n]]) };
  const aux = a => v.aux === 'hz' ? AUX.h[a] + ' / ' + AUX.z[a] : AUX[v.aux][a];
  return { head: ['', ''], rows: PERS.map(([l, p, n]) => [l, aux(n === 'pl' ? 'pl' : p) + ' ' + v.f.vd]) };
}
Object.keys(cards).forEach(k => {
  const c = cards[k], spec = c.irr;
  if (!spec) return;
  c.irr = spec.verbs.map(inf => {
    const v = VERBS.find(x => x.v === inf);
    if (!v || !v.f[spec.tense === 'ovt' ? 'ovt' : 'vd']) { bad.push(k + ': no verb ' + inf); return null; }
    return Object.assign({ v: inf, en: v.en }, irrTable(v, spec.tense));
  }).filter(Boolean);
});
if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
const out = `/* GENERATED by tools/nl/build-cards.js from tools/nl/src/cards.json. Do not edit.
 * ${Object.keys(cards).length} cards. */
(function (w) {
w.NL_CARDS = ${JSON.stringify(cards, null, 1)};
if (typeof module !== "undefined" && module.exports) module.exports = w.NL_CARDS;
})(typeof window !== "undefined" ? window : globalThis);
`;
fs.writeFileSync(path.join(ROOT, 'nederlands', 'data', 'cards.js'), out);
console.log(Object.keys(cards).length + ' cards -> nederlands/data/cards.js');
