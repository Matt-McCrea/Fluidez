// Splits the two biggest data files by CEFR band so the page only loads the bands a learner needs.
//   data/strand-lessons.js  ->  data/lessons/<band>.js   (window.STRAND_LESSONS_<BAND>)
//   data/requires.js        ->  data/requires/<band>.js  (window.REQUIRES_<BAND>)
//   plus data/lessons/index.js (window.LESSONS_INDEX: counts per band and the band of every lesson id)
// The two big files stay in place as the source of truth for node tools (tag-data writes requires.js,
// authors edit strand-lessons.js); the browser never loads them. Run:  npx tsx tools/split-data.ts
//   --check   exit 1 if the split files differ from what a split would write now
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import vm from 'node:vm';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const BANDS = ['A1', 'A2', 'B1', 'B2', 'C1'];

type Band = string;
export type Split = { files: Record<string, string>; counts: Record<string, any> };

export function buildSplit(): Split {
  const ctx: any = { window: {}, console };
  vm.createContext(ctx);
  for (const f of ['data/taxonomy.js', 'data/connectors.js', 'data/rubrics.js', 'data/strand-lessons.js', 'data/course.js', 'data/verbs.js',
    'data/vocab.js', 'data/idioms.js', 'data/grammar-docs.js', 'data/grammar.js', 'data/passages.js', 'data/apply.js', 'data/writing.js',
    'data/topics.js', 'js/engine.js', 'js/lessons.js', 'data/requires.js']) vm.runInContext(readFileSync(join(ROOT, f), 'utf8'), ctx, { filename: f });
  const W = ctx.window;

  /* gate level -> band; levels shared by two bands (3, 4, 5) go to the lowest, which every higher learner also loads */
  const levelBand = (lv: number): Band => {
    for (const l of W.LEVELS as any[]) if ((l.levels as number[]).includes(lv)) return l.code;
    return 'A1';
  };

  /* ---- lessons ---- */
  const strand: any[] = W.STRAND_LESSONS;
  const bandOfLesson = new Map<string, Band>();
  for (const l of strand) bandOfLesson.set(l.id, BANDS.includes(l.cefr) ? l.cefr : 'A1');
  /* A merge fuses lessons (MERGES in js/lessons.js). Strand lessons that merge into one go to the first one's
   * band, so a learner who has the head always has the rest and the merge never half-applies. */
  let moved = 0;
  for (const ids of W.LESSON_MERGE_GROUPS as string[][]) {
    const parts = ids.filter((id) => bandOfLesson.has(id));
    if (parts.length < 2) continue;
    const b = bandOfLesson.get(parts[0])!;
    for (const id of parts) if (bandOfLesson.get(id) !== b) { bandOfLesson.set(id, b); moved++; }
  }
  const files: Record<string, string> = {};
  const counts: Record<string, any> = {};
  const lessonsBy: Record<Band, any[]> = {};
  for (const b of BANDS) lessonsBy[b] = [];
  for (const l of strand) lessonsBy[bandOfLesson.get(l.id)!].push(l);

  /* tense and concept lessons are not strand lessons; their requires rows go by their level */
  const otherBand = new Map<string, Band>();
  for (const l of W.ALL_LESSONS as any[]) if (!bandOfLesson.has(l.id)) otherBand.set(l.id, BANDS.includes(l.cefr) ? l.cefr : levelBand(l.level ?? 1));
  for (const l of W.SEED_SYLLABUS as any[]) if (!bandOfLesson.has(l.id) && !otherBand.has(l.id)) otherBand.set(l.id, levelBand(l.level ?? 1));
  const lessonBand = (id: string): Band => bandOfLesson.get(id) ?? otherBand.get(id) ?? 'A1';

  for (const b of BANDS) {
    const rows = lessonsBy[b].map((l) => JSON.stringify(l));
    files[`data/lessons/${b.toLowerCase()}.js`] =
      `/* GENERATED by tools/split-data.ts from data/strand-lessons.js. Do not edit. ${b} strand lessons. */\nwindow.STRAND_LESSONS_${b} = [\n${rows.join(',\n')}\n];\n`;
    counts[b] = { lessons: rows.length };
  }

  /* ---- requires ---- */
  const REQ: Record<string, any> = W.REQUIRES;
  const passage = new Map<string, number>((W.PASSAGES as any[]).map((p) => [p.id, p.level]));
  const writing = new Map<string, number>((W.WRITING_TASKS as any[]).map((t) => [t.id, t.level]));
  const apply: any[] = W.APPLY_ITEMS;
  const reqBy: Record<Band, Record<string, any>> = {};
  for (const b of BANDS) reqBy[b] = {};
  const unknown: string[] = [];
  const bandOfKey = (k: string): Band => {
    const [kind, id] = [k.slice(0, k.indexOf(':')), k.slice(k.indexOf(':') + 1)];
    if (kind === 'passage') { const lv = passage.get(id); if (lv != null) return levelBand(lv); }
    else if (kind === 'apply') { const it = apply[Number(id)]; if (it) return levelBand(it.level ?? 1); }
    else if (kind === 'writing') { const lv = writing.get(id); if (lv != null) return levelBand(lv); }
    else if (kind === 'lesson') return lessonBand(id.replace(/:ex:\d+$/, ''));
    else if (kind === 'idiom' || kind === 'topic') return 'A1';
    unknown.push(k);
    return 'A1';
  };
  for (const k of Object.keys(REQ).sort()) reqBy[bandOfKey(k)][k] = REQ[k];
  for (const b of BANDS) {
    const lines = Object.keys(reqBy[b]).map((k) => `${JSON.stringify(k)}:${JSON.stringify(reqBy[b][k])}`);
    files[`data/requires/${b.toLowerCase()}.js`] =
      `/* GENERATED by tools/split-data.ts from data/requires.js. Do not edit. ${b} content id -> graph nodes it requires. */\nwindow.REQUIRES_${b} = {\n${lines.join(',\n')}\n};\n`;
    counts[b].requires = lines.length;
  }
  if (unknown.length) console.warn(`split-data: ${unknown.length} requires keys of an unknown kind went to A1, e.g. ${unknown.slice(0, 3).join(', ')}`);

  const ids: Record<string, Band> = {};
  for (const [id, b] of bandOfLesson) ids[id] = b;
  files['data/lessons/index.js'] =
    `/* GENERATED by tools/split-data.ts. Do not edit. Counts per band and the band file each strand lesson lives in. */\nwindow.LESSONS_INDEX = ${JSON.stringify({ bands: counts, ids })};\n`;
  (counts as any).__moved = moved;
  return { files, counts };
}

export function writeSplit(): Split {
  const s = buildSplit();
  mkdirSync(join(ROOT, 'data/lessons'), { recursive: true });
  mkdirSync(join(ROOT, 'data/requires'), { recursive: true });
  for (const [f, body] of Object.entries(s.files)) writeFileSync(join(ROOT, f), body);
  return s;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const s = buildSplit();
    const stale = Object.entries(s.files).filter(([f, body]) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), 'utf8') !== body).map(([f]) => f);
    if (stale.length) { console.error('data split is stale: ' + stale.join(', ') + '. Run: npx tsx tools/split-data.ts'); process.exit(1); }
    console.log('data split is up to date.');
  } else {
    const s = writeSplit();
    for (const b of BANDS) console.log(`${b}: ${s.counts[b].lessons} lessons, ${s.counts[b].requires} requires rows`);
    console.log(`${s.counts.__moved} merge partners moved to their head's band.`);
  }
}
