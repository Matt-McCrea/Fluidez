// Brings the rebuild's contrast store and scripted scenes into the ORIGINAL app's data (new files only).
// Writes data/contrasts/{index,items}.js, data/scenes/<band>.js, data/scenes/index.js, docs/plan-2026-11-04/content-import.md
// Run:  nice npx tsx tools/content-import.ts
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import vm from 'node:vm';
import { castNames, loadGraph, tagOptions, taughtAt, type Graph } from '../lib/graph';
import { tagRow } from '../lib/tagger/tagAll';
import { gapOptionOk, hasDash, servingLegalDay } from './content-import-lib';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const t0 = Date.now();
const rd = (p: string) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

/* graph + tagger options */
const gdir = join(ROOT, 'app/content/graph');
const raw = readdirSync(gdir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort().map((f) => rd(`app/content/graph/${f}`));
const graph: Graph = loadGraph(raw);
const udir = join(ROOT, 'app/content/units');
const unitFiles = readdirSync(udir).filter((f) => /^u\d+\.json$/.test(f)).sort();
const units = new Map<string, any>(unitFiles.map((f) => { const u = rd(`app/content/units/${f}`); return [u.id, u]; }));
const opts = tagOptions(graph, { names: castNames([...units.values()].map((u) => u.storyArc ?? '').join(' ')) });

/* old spine */
const ctx: any = { window: {}, console };
vm.createContext(ctx);
for (const f of ['data/course.js', 'data/lesson-nodes.js']) vm.runInContext(readFileSync(join(ROOT, f), 'utf8'), ctx, { filename: f });
const days: Array<{ lesson?: string | null }> = ctx.window.COURSE_DAYS;
const LN = ctx.window.LESSON_NODES as Record<string, { teaches?: string[] }>;
const order: string[] = []; const dayOfPos: number[] = [];
days.forEach((d, i) => { for (const n of (d.lesson && LN[d.lesson]?.teaches) || []) { order.push(n); dayOfPos.push(i); } });
const taught = new Map<string, number>();
for (const [id, pos] of taughtAt(graph, order)) taught.set(id, dayOfPos[pos]);
const nDays = days.length;
const ld = (reqs: string[]) => servingLegalDay(graph, taught, reqs, nDays);
const taughtOn = (id: string) => taught.has(id);

const dashFindings: string[] = [];
const dashCheck = (where: string, s: string | undefined) => { if (s && hasDash(s)) dashFindings.push(`${where}: ${s.slice(0, 90)}`); };
const notes: string[] = [];
const sz = (p: string) => Math.round(statSync(join(ROOT, p)).size / 1024);

/* ---------- contrasts ---------- */
const cdir = join(ROOT, 'app/content/contrasts');
const cfiles = readdirSync(cdir).filter((f) => /^x_.*\.json$/.test(f)).sort();
const items: any[] = []; const index: any[] = []; const perContrast: any[] = [];
let badGap = 0;
for (const f of cfiles) {
  const cf = rd(`app/content/contrasts/${f}`);
  const node = graph.nodes.get(cf.node) as any;
  const sideIds: string[] = [...new Set<string>([...(node?.contrasts ?? []), ...cf.items.map((i: any) => i.side)])];
  let minD: number | null = null; let kept = 0;
  for (const it of cf.items) {
    ['es', 'en', 'why'].forEach((k) => dashCheck(`${it.id}.${k}`, it[k]));
    it.options.forEach((o: string, n: number) => dashCheck(`${it.id}.options[${n}]`, o));
    if (!gapOptionOk(it)) { badGap++; notes.push(`gap/option mismatch ${it.id}`); continue; }
    const t = tagRow({ id: it.id, es: it.es }, opts);
    const d = ld(t.requires);
    if (d !== null && (minD === null || d < minD)) minD = d;
    items.push({ id: it.id, x: cf.node, side: it.side, rung: it.rung, es: it.es, en: it.en, gap: it.gap, options: it.options, answer: it.answer, why: it.why, r: t.requires, d });
    kept++;
  }
  const sideTaught = Object.fromEntries(sideIds.map((s) => [s, taughtOn(s)]));
  const nTaught = Object.values(sideTaught).filter(Boolean).length;
  const mix = sideIds.length >= 2 && nTaught === sideIds.length;
  index.push({ id: cf.node, node: cf.node, title: node?.title ?? cf.node, decides: cf.decides,
    sides: sideIds.map((s) => ({ id: s, label: (graph.nodes.get(s) as any)?.title ?? (graph.nodes.get(s) as any)?.label ?? s })), legalDay: minD });
  perContrast.push({ id: cf.node, n: kept, legalDay: minD, mix, nTaught, sides: sideIds.length, decides: cf.decides, usable: items.filter((i) => i.x === cf.node && i.d !== null).length });
}
const wrapJs = (hdr: string, name: string, arr: unknown[]) =>
  `/* GENERATED by tools/content-import.ts. Do not edit. ${hdr} */\nwindow.${name} = [\n${arr.map((r) => JSON.stringify(r)).join(',\n')}\n];\n`;
writeFileSync(join(ROOT, 'data/contrasts/index.js'), wrapJs('Contrasts of the rebuild (title, what decides it, sides, earliest legal day on the old spine).', 'CONTRASTS', index));
writeFileSync(join(ROOT, 'data/contrasts/items.js'), wrapJs('Contrast items: x contrast, side, rung, es/en, gap [start,end] in es, options, answer, why, r requires, d legal day (null = never served).', 'CONTRAST_ITEMS', items));

/* ---------- scenes ---------- */
const sdir = join(ROOT, 'app/content/scenes');
const sfiles = readdirSync(sdir).filter((f) => f.endsWith('.json')).sort();
const byBand = new Map<string, any[]>(); const sidx: any[] = [];
const blockers = new Map<string, number>();
const sceneStats = new Map<string, { n: number; legal: number; never: number }>();
for (const f of sfiles) {
  const s = rd(`app/content/scenes/${f}`);
  const u = units.get(s.unit); const band: string = u?.band ?? 'A1';
  if (!u) notes.push(`scene ${s.id}: unknown unit ${s.unit}`);
  dashCheck(`${s.id}.title`, s.title); dashCheck(`${s.id}.brief`, s.brief);
  const strings: string[] = [];
  for (const t of s.turns) {
    ['npc', 'npcEn', 'intent'].forEach((k) => dashCheck(`${s.id}/${t.id}.${k}`, t[k]));
    t.accept.forEach((a: string, n: number) => dashCheck(`${s.id}/${t.id}.accept[${n}]`, a));
    strings.push(t.npc, ...t.accept);
  }
  const reqs = new Set<string>();
  strings.forEach((es, i) => { for (const r of tagRow({ id: `${s.id}#${i}`, es }, opts).requires) { const n = graph.nodes.get(r); if (n && n.kind !== 'lexeme') reqs.add(r); } });
  const r = [...reqs].sort();
  const d = ld(r);
  const st = sceneStats.get(band) ?? { n: 0, legal: 0, never: 0 };
  st.n++; if (d === null) { st.never++; for (const x of r) if ((x.startsWith('g:') || x.startsWith('x:')) && !taught.has(x)) blockers.set(x, (blockers.get(x) ?? 0) + 1); } else st.legal++;
  sceneStats.set(band, st);
  const out: any = { id: s.id, unit: s.unit, band, title: s.title, brief: s.brief, turns: s.turns, r, d };
  if (s.spare) out.spare = true;
  if (['u01', 'u02', 'u03'].includes(s.unit)) out.review = true;
  const arr = byBand.get(band) ?? []; arr.push(out); byBand.set(band, arr);
  sidx.push({ id: s.id, band, title: s.title, legalDay: d, file: `data/scenes/${band.toLowerCase()}.js` });
}
for (const [band, arr] of byBand) writeFileSync(join(ROOT, `data/scenes/${band.toLowerCase()}.js`),
  wrapJs(`Scripted scenes, band ${band}. r = non-lexeme requires over npc lines and accepts, d = legal day (null = never served), review = needs rewriting.`, `SCENES_${band}`, arr).replace('window.SCENES_' + band + ' = [', `window.SCENES_${band} = [`));
writeFileSync(join(ROOT, 'data/scenes/index.js'), wrapJs('Scene index, ids in rebuild order.', 'SCENE_INDEX', sidx).replace('window.SCENE_INDEX = [', 'window.SCENE_INDEX = ['));

/* ---------- report ---------- */
const md: string[] = ['# Content import: contrasts and scenes', '', 'Generated by `tools/content-import.ts` (`nice npx tsx tools/content-import.ts`). New files only; nothing existing is touched.', ''];
md.push('## Files', '', ...['data/contrasts/index.js', 'data/contrasts/items.js', 'data/scenes/index.js', ...[...byBand.keys()].map((b) => `data/scenes/${b.toLowerCase()}.js`)].map((p) => `- ${p}: ${sz(p)} KB`), '');
md.push('## Legal day (serving rule)', '', 'legalDay = latest taught day over the non-lexeme requires. A required `g:` or `x:` node the old course never teaches blocks (null). `p:` and `c:` block only through the day they are taught; never-taught ones do not block. `l:` never blocks. Days index COURSE_DAYS (' + nDays + ' days).', '');
const tot = perContrast.reduce((a, c) => a + c.n, 0), usable = items.filter((i) => i.d !== null).length;
md.push(`## Contrasts`, '', `${cfiles.length} contrasts, ${tot} items kept (${badGap} dropped for gap/option mismatch), ${usable} with a legal day, ${tot - usable} never served on the old spine.`, '');
const both = perContrast.filter((c) => c.mix), one = perContrast.filter((c) => !c.mix && c.nTaught > 0), none = perContrast.filter((c) => c.nTaught === 0);
md.push(`Both sides taught on the old spine (mixable): ${both.length}. One side only: ${one.length}. Neither: ${none.length}.`, '');
md.push('| contrast | decides | items | usable | legalDay | sides taught |', '|---|---|---|---|---|---|');
for (const c of perContrast) md.push(`| ${c.id} | ${c.decides} | ${c.n} | ${c.usable} | ${c.legalDay ?? 'never'} | ${c.nTaught}/${c.sides}${c.mix ? ' mix' : ''} |`);
md.push('', '## Scenes', '', '| band | scenes | with legal day | never |', '|---|---|---|---|');
for (const [b, s] of sceneStats) md.push(`| ${b} | ${s.n} | ${s.legal} | ${s.never} |`);
md.push('', 'Scenes of u01 to u03 are marked `review: true`.', '', 'Top blocking nodes (never-taught g:/x: nodes, scenes blocked):', '');
[...blockers].sort((a, b) => b[1] - a[1]).slice(0, 15).forEach(([n, c]) => md.push(`- ${n}: ${c}`));
md.push('', '## Dash findings', '', dashFindings.length ? `${dashFindings.length} learner strings contain a dash:` : 'None.', '', ...dashFindings.slice(0, 60).map((d) => `- ${d}`));
if (notes.length) md.push('', '## Did not import cleanly', '', ...notes.map((n) => `- ${n}`));
writeFileSync(join(ROOT, 'docs/plan-2026-11-04/content-import.md'), md.join('\n') + '\n');
console.log(JSON.stringify({ secs: (Date.now() - t0) / 1000, contrasts: cfiles.length, items: tot, usable, badGap, mix: both.length, one: one.length, none: none.length, scenes: sidx.length, sceneStats: [...sceneStats], dashes: dashFindings.length, notes: notes.length, topBlockers: [...blockers].sort((a, b) => b[1] - a[1]).slice(0, 5) }));
