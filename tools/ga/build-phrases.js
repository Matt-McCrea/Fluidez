#!/usr/bin/env node
/* build-phrases.js: gaeilge/data/phrases.js (window.GA_PHRASES) for Frásaí,
 * from tools/ga/src/phrases/*.json: { ga, en, alt?, th, b, t, n? }, in the
 * order written within each tier (tier 1 first). Rejects dashes, duplicates,
 * phrases over 8 words, bad bands or tiers. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const dir = path.join(__dirname, 'src', 'phrases');
const out = [], bad = [], seen = {};
fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().forEach(f => {
  JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).forEach((p, i) => {
    const at = `${f}#${i} ${p.ga}`;
    if (!p.ga || !p.en || !p.th) return bad.push(at + ': needs ga, en, th');
    if (['A1', 'A2', 'B1', 'B2'].indexOf(p.b) === -1) return bad.push(at + ': band');
    if ([1, 2, 3].indexOf(p.t) === -1) return bad.push(at + ': tier');
    if (/[–—]|\s-\s/.test(JSON.stringify(p))) return bad.push(at + ': dash');
    if (p.ga.replace(/[.,;:!?]/g, '').trim().split(/\s+/).length > 8) return bad.push(at + ': over 8 words');
    if (seen[p.ga]) return bad.push(at + ': duplicate');
    seen[p.ga] = 1;
    out.push(Object.assign({ _o: out.length }, p));
  });
});
out.sort((a, b) => a.t - b.t || a._o - b._o);
out.forEach(p => delete p._o);
bad.forEach(b => console.log('  ✗ ' + b));
fs.writeFileSync(path.join(ROOT, 'gaeilge', 'data', 'phrases.js'),
  `/* GENERATED by tools/ga/build-phrases.js from tools/ga/src/phrases/. Do not edit. ${out.length} phrases. */\n` +
  '(function (w) {\nw.GA_PHRASES = [\n' + out.map(p => JSON.stringify(p)).join(',\n') +
  '\n];\nif (typeof module !== "undefined" && module.exports) module.exports = w.GA_PHRASES;\n})(typeof window !== "undefined" ? window : globalThis);\n');
console.log(out.length + ' phrases, ' + bad.length + ' rejected');
