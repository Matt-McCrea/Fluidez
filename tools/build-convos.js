#!/usr/bin/env node
/* Example conversations, for every app: tools/convos/<lang>.json into the app's
 * data/conversations.js, gated.
 *   node tools/build-convos.js es|ga|ar|ru [--check]
 *
 * A conversation: { id, en (title), th (a phrase theme id), b (band), you: 'a'|'b',
 *   roles: { a: 'You', b: 'Waiter' } (English), n?: note,
 *   lines: [ { who: 'a'|'b', en, <text> } ] }
 * The text field per language:
 *   es: es            ga: ga            ru: ru (stress as an apostrophe after the vowel)
 *   ar: msa, lev, egy (msa fully vowelled; lev and egy as written in phrases.json)
 *       and tr: { msa, lev, egy } (the hand-written learner transliteration)
 * Gate: 5 to 12 lines, both roles speak, the learner's role has at least 3 lines,
 * ids unique, no dashes in English, Russian stressed, Arabic fuṣḥā vowelled.
 * Output global: ES_CONVOS (data/conversations.js at the root, for Juegos),
 * GA_CONVOS (gaeilge/data), AR_CONVOS (arabiya/data), RU_CONVOS (russkiy/data). */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const lang = process.argv[2];
const CHECK = process.argv.includes('--check');
const OUT = { es: ['data', 'ES_CONVOS'], ga: ['gaeilge/data', 'GA_CONVOS'], ar: ['arabiya/data', 'AR_CONVOS'], ru: ['russkiy/data', 'RU_CONVOS'] }[lang];
if (!OUT) { console.log('usage: node tools/build-convos.js es|ga|ar|ru [--check]'); process.exit(2); }
const src = path.join(__dirname, 'convos', lang + '.json');
const C = JSON.parse(fs.readFileSync(src, 'utf8'));
const RU = lang === 'ru' ? require(path.join(ROOT, 'russkiy/js/ru-text.js')) : null;
const AR = lang === 'ar' ? require(path.join(ROOT, 'arabiya/js/ar-text.js')) : null;

let errs = 0;
const bad = (id, m) => { errs++; console.log(id + ': ' + m); };
const DASH = /[–—]|\s-\s/;
const ids = new Set();
C.forEach(c => {
  const id = c.id || '(no id)';
  if (!c.id || !c.en || !c.th || !c.b || !c.roles || !c.lines) return bad(id, 'needs id, en, th, b, roles, lines');
  if (ids.has(c.id)) bad(id, 'duplicate id'); ids.add(c.id);
  if (!/^[ab]$/.test(c.you || '')) bad(id, 'you must be a or b');
  if (DASH.test(c.en + (c.n || '') + c.roles.a + c.roles.b)) bad(id, 'dash');
  if (c.lines.length < 5 || c.lines.length > 12) bad(id, c.lines.length + ' lines (5 to 12)');
  const mine = c.lines.filter(l => l.who === c.you).length;
  if (mine < 3) bad(id, 'the learner speaks only ' + mine + ' times');
  if (!c.lines.some(l => l.who !== c.you)) bad(id, 'only one role speaks');
  c.lines.forEach((l, i) => {
    const at = id + '#' + i;
    if (!/^[ab]$/.test(l.who || '')) bad(at, 'who must be a or b');
    if (!l.en) bad(at, 'no English');
    if (DASH.test(l.en || '')) bad(at, 'dash in English');
    if (lang === 'es' && !l.es) bad(at, 'no es');
    if (lang === 'ga' && !l.ga) bad(at, 'no ga');
    if (lang === 'ru') {
      if (!l.ru) return bad(at, 'no ru');
      l.ru = RU.fromApostrophe(l.ru);
      if (/'/.test(l.ru)) bad(at, 'stray apostrophe');
      const u = RU.unstressed(l.ru); if (u.length) bad(at, 'no stress on ' + u.join(' '));
      l.tr = l.tr || RU.translit(l.ru);
    }
    if (lang === 'ar') {
      if (!l.msa || !l.lev || !l.egy) return bad(at, 'needs msa, lev and egy');
      const u = AR.unvowelled(l.msa); if (u.length) bad(at, 'msa not fully vowelled: ' + u.join(' '));
      if (!l.tr || !l.tr.msa || !l.tr.lev || !l.tr.egy) bad(at, 'needs tr for msa, lev and egy');
      else if (DASH.test(l.tr.msa + l.tr.lev + l.tr.egy)) bad(at, 'dash in tr');
    }
    const text = l[lang === 'ar' ? 'msa' : lang];
    if (text && DASH.test(text)) bad(at, 'dash in the text');
  });
});
console.log(C.length + ' conversations, ' + C.reduce((n, c) => n + c.lines.length, 0) + ' lines' + (errs ? ', ' + errs + ' errors' : ''));
if (errs) process.exit(1);
if (CHECK) process.exit(0);
fs.writeFileSync(path.join(ROOT, OUT[0], 'conversations.js'),
  '/* Example conversations: generated by tools/build-convos.js from tools/convos/' + lang + '.json. Do not edit. */\n' +
  '(function (root) {\n  var C = ' + JSON.stringify(C) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = C;\n  else root.' + OUT[1] + ' = C;\n})(this);\n');
