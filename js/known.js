/* ============================================================================
 * KNOWN — what the learner has met, as graph nodes, and which items they may be
 * served. Replaces the tense gate in js/session.js with node gating.
 *
 *   taughtBy(di)          nodes taught by course day `di`, inclusive (memoised)
 *   forLearner(prog, di)  taughtBy(di) + lessons marked studied + nodes passed in review
 *   todayNodes(focus, di) the nodes today's day is about
 *   allows(key, known, today, band)   may this item be served?
 *   targets(key, today)   does this item exercise today's nodes?
 *
 * Reads data at run time (LESSON_NODES is regenerated by tools/tag-data.ts):
 * never hardcode a node id here.
 *
 * THE SERVING RULE (stricter than the content gate's lateRequires, on purpose).
 * The gate lets never-taught nodes through because it checks authored rows
 * against a course that does not claim to teach everything. Serving is the
 * other way round: a row that needs `g:reported-backshift` must never reach a
 * learner who has not met it, whether or not any lesson ever teaches it.
 *   g: and x:   block unless in known or today
 *   p: and c:   block only when the course teaches them LATER than today
 *               (never-taught patterns and chunks are allowed)
 *   l:          never blocks; ids the graph does not know never block
 * ========================================================================== */
window.Known = (function () {
  var graph = null, firstDay = null, memo = new Map(), MEMO_MAX = 24;
  var stats = { missing: 0 };

  function init() {
    if (firstDay) return true;
    if (!window.GRAPH || !window.LIB || !window.LIB.graph) return false;
    graph = window.LIB.graph.loadGraph(window.GRAPH.nodes);
    var LN = window.LESSON_NODES || {}, order = [], dayOf = [];
    (window.COURSE_DAYS || []).forEach(function (d, i) {
      if (!d.lesson || !LN[d.lesson]) return;
      (LN[d.lesson].teaches || []).forEach(function (id) { order.push(id); dayOf.push(i); });
    });
    // first position each node is taught at; a taught chunk also teaches what it unpacks
    var at = window.LIB.graph.taughtAt(graph, order);
    firstDay = new Map();
    at.forEach(function (pos, id) { firstDay.set(id, dayOf[pos]); });
    return true;
  }
  function reset() { graph = null; firstDay = null; memo = new Map(); stats.missing = 0; cognates = null; dayMemo = new Map(); }

  function taughtBy(di) {
    if (!init()) return new Set();
    if (memo.has(di)) return memo.get(di);
    var s = new Set();
    firstDay.forEach(function (d, id) { if (d <= di) s.add(id); });
    if (memo.size >= MEMO_MAX) memo.delete(memo.keys().next().value);
    memo.set(di, s);
    return s;
  }

  function teachesOf(lessonId) {
    var e = (window.LESSON_NODES || {})[lessonId];
    return e && e.teaches ? e.teaches : [];
  }

  // Review passes: g:/p:/c:/x: ids with at least one right answer; v:<es>:meaning -> l:<es>
  function passedInReview() {
    var out = [], srs = {};
    try { srs = JSON.parse(localStorage.getItem('fluidez.srs')) || {}; } catch (e) { srs = {}; }
    Object.keys(srs).forEach(function (id) {
      var r = srs[id] || {};
      if (!((r.reps || 0) > (r.lapses || 0) || r.consecCorrect > 0)) return;
      if (/^[gpcx]:/.test(id)) out.push(id);
      else {
        var m = /^v:(.+):meaning$/.exec(id);
        if (m && graph && graph.ids.has('l:' + m[1])) out.push('l:' + m[1]);
      }
    });
    return out;
  }

  /* ---- WORDS THE LEARNER KNOWS, as `l:<lemma>` ids ---------------------------
   * The graph's lexeme nodes were never in taughtBy (no lesson `teaches` them),
   * so reading coverage came out near zero. A word counts as known when:
   *   - it is a keyword or exponent of a lesson the course has reached by day
   *     `di` or the learner has studied, or the infinitive of a verb day;
   *   - it is in the new-word drip so far: VOCAB entries at or below the band
   *     of day `di`, in VOCAB order, at SRS.NEW_TARGET a day for the days spent
   *     in each band (VOCAB carries no first course day, so pace stands in for
   *     it), plus any word the learner has enrolled in review;
   *   - it is a transparent cognate of its English gloss (same first four
   *     letters once accents are stripped, or -ción/-tion, -dad/-ty, -mente/-ly,
   *     -oso/-ous, -ico/-ic), because the plan counts cognates as known. */
  var RANKS = ['A1', 'A2', 'B1', 'B2', 'C1'];
  var cognates = null, vocabByBand = null, lessonById = null, lexIds = null, dayMemo = new Map();
  function bareEs(es) { return String(es || '').trim().toLowerCase().replace(/^(el|la|los|las|un|una)\s+/, ''); }
  function plain(w) { return String(w).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, ''); }
  var SUFFIX = [['cion', 'tion'], ['dad', 'ty'], ['mente', 'ly'], ['oso', 'ous'], ['osa', 'ous'], ['ico', 'ic'], ['ica', 'ic']];
  function isCognate(es, en) {
    var a = plain(bareEs(es)), b = plain(String(en || '').toLowerCase().replace(/^(to|the|a|an)\s+/, '').split(/[,;(\/]/)[0].trim());
    if (!a || !b || a.indexOf(' ') !== -1 || b.indexOf(' ') !== -1) return false;
    if (a.length >= 4 && b.length >= 4 && a.slice(0, 4) === b.slice(0, 4)) return true;
    for (var i = 0; i < SUFFIX.length; i++) {
      var x = SUFFIX[i][0], y = SUFFIX[i][1];
      if (a.length > x.length && b.length > y.length && a.slice(-x.length) === x && b.slice(-y.length) === y) return true;
    }
    return false;
  }
  function prepLex() {
    if (cognates) return;
    cognates = new Set(); lexIds = new Set();
    (window.GRAPH && window.GRAPH.nodes || []).forEach(function (n) {
      if (n.kind !== 'lexeme') return;
      lexIds.add(n.id);
      if (isCognate(n.es, n.en)) cognates.add(n.id);
    });
    vocabByBand = {}; RANKS.forEach(function (b) { vocabByBand[b] = []; });
    (window.VOCAB || []).forEach(function (w) { if (w.es && vocabByBand[w.cefr || 'A1']) vocabByBand[w.cefr || 'A1'].push(bareEs(w.es)); });
    lessonById = {};
    (window.Lessons && window.Lessons.withAliasSources ? window.Lessons.withAliasSources() : (window.GRAMMAR_LESSONS || [])).forEach(function (l) { if (l) lessonById[l.id] = l; });
  }
  function bandOfDay(di) {
    var starts = window.COURSE_BANDS || {}, b = 'A1';
    RANKS.forEach(function (r) { if (starts[r] != null && starts[r] <= di) b = r; });
    return b;
  }
  function addLex(set, lemma) { if (lemma) set.add('l:' + lemma); }
  function addPhrase(set, es) {
    var b = bareEs(es);
    addLex(set, b);
    (b.match(/[\p{L}]{4,}/gu) || []).forEach(function (w) { if (lexIds.has('l:' + w)) set.add('l:' + w); });
  }
  function taughtWords(di) {
    if (dayMemo.has(di)) return dayMemo.get(di);
    var out = new Set(), days = window.COURSE_DAYS || [];
    for (var i = 0; i <= di && i < days.length; i++) {
      var d = days[i];
      if (d.verbs) d.verbs.forEach(function (v) { addLex(out, bareEs(v).replace(/se$/, '')); addLex(out, bareEs(v)); });
      var l = d.lesson && lessonById[d.lesson];
      if (l) [].concat(l.keywords || [], l.exponents || []).forEach(function (k) { if (k && k.es) addPhrase(out, k.es); });
    }
    var starts = window.COURSE_BANDS || {}, here = RANKS.indexOf(bandOfDay(di)), target = (window.SRS && window.SRS.NEW_TARGET) || {};
    RANKS.forEach(function (b, bi) {
      if (bi > here) return;
      var from = starts[b] || 0, to = bi < here ? (starts[RANKS[bi + 1]] != null ? starts[RANKS[bi + 1]] : di + 1) : di + 1;
      var n = Math.max(0, to - from) * (target[b] || 10);
      vocabByBand[b].slice(0, n).forEach(function (w) { addLex(out, w); });
    });
    if (dayMemo.size >= MEMO_MAX) dayMemo.delete(dayMemo.keys().next().value);
    dayMemo.set(di, out);
    return out;
  }
  function enrolledWords() {
    var out = [], srs = {};
    try { srs = JSON.parse(localStorage.getItem('fluidez.srs')) || {}; } catch (e) { srs = {}; }
    Object.keys(srs).forEach(function (id) { var m = /^v:(.+):meaning$/.exec(id); if (m) out.push('l:' + bareEs(m[1])); });
    return out;
  }

  function forLearner(prog, di) {
    if (!init()) return new Set();
    prepLex();
    var s = new Set(taughtBy(di));
    cognates.forEach(function (id) { s.add(id); });
    taughtWords(di).forEach(function (id) { s.add(id); });
    enrolledWords().forEach(function (id) { s.add(id); });
    ((prog && prog.studied) ? Object.keys(prog.studied) : []).forEach(function (lid) {
      var l = lessonById[lid];
      if (l) [].concat(l.keywords || [], l.exponents || []).forEach(function (k) { if (k && k.es) addPhrase(s, k.es); });
    });
    var studied = (prog && prog.studied) || {};
    Object.keys(studied).forEach(function (id) { teachesOf(id).forEach(function (n) { s.add(n); }); });
    passedInReview().forEach(function (n) { s.add(n); });
    return s;
  }

  /* Verb days exercise the regular present (and the odd stem change). Mapped by
   * ending, with ser/estar and the stem-changers named; only ids the graph has. */
  var STEM_BOOT = 'querer poder dormir jugar preferir pensar volver encontrar empezar entender almorzar recordar costar sentir mostrar'.split(' ');
  var STEM_EI = 'pedir servir seguir repetir decir'.split(' ');
  function verbNodes(verbs) {
    var out = new Set();
    (verbs || []).forEach(function (v) {
      var id = null;
      if (v === 'ser') id = 'g:ser-identity';
      else if (v === 'estar') id = 'g:estar-location-states';
      else if (/ar(se)?$/.test(v)) id = 'g:present-ar';
      else if (/(er|ir)(se)?$/.test(v)) id = 'g:present-er-ir';
      if (id) out.add(id);
      var b = v.replace(/se$/, '');
      if (STEM_BOOT.indexOf(b) !== -1) out.add('g:stem-boot');
      if (STEM_EI.indexOf(b) !== -1) out.add('g:stem-e-i');
    });
    var res = new Set();
    out.forEach(function (id) { if (graph && graph.ids.has(id)) res.add(id); });
    return res;
  }

  /* The week's Introduce lesson for a practice day: the first lesson day of kind 'introduce' in the unit
   * at or before `di`. Null when the course carries no kinds (the pre-resequence course) or no such day. */
  function introLesson(focus, di) {
    var days = window.COURSE_DAYS || [];
    var u = focus && focus.unit && window.COURSE_UNITS && window.COURSE_UNITS[focus.unit];
    if (!u || u.from == null) return null;
    for (var i = u.from; i <= di && i < days.length && i < u.from + u.length; i++) {
      if (days[i] && days[i].lesson && days[i].kind === 'introduce') return days[i].lesson;
    }
    return null;
  }
  function introNodes(focus, di) {
    var s = new Set(), id = introLesson(focus, di);
    if (id) teachesOf(id).forEach(function (n) { s.add(n); });
    return s;
  }

  function todayNodes(focus, di) {
    var s = new Set();
    if (!init() || !focus) return s;
    var days = window.COURSE_DAYS || [];
    if (focus.type === 'grammar' && focus.id) { teachesOf(focus.id).forEach(function (n) { s.add(n); }); return s; }
    if (focus.type === 'verbs') return verbNodes(focus.verbs);
    // practice day: the nodes of the unit's lessons so far (or the last six days if it has no unit),
    // the week's Introduce lesson first
    var from = Math.max(0, di - 6);
    var u = focus.unit && window.COURSE_UNITS && window.COURSE_UNITS[focus.unit];
    if (u && u.from != null) from = u.from;
    introNodes(focus, di).forEach(function (n) { s.add(n); });
    for (var i = from; i <= di && i < days.length; i++) {
      if (days[i] && days[i].lesson) teachesOf(days[i].lesson).forEach(function (n) { s.add(n); });
    }
    return s;
  }

  var BAND_RANK = { A1: 0, A2: 1, B1: 2, B2: 3, C1: 4 };
  function allows(key, known, today, band) {
    if (!init()) return true;
    var e = (window.REQUIRES || {})[key];
    if (!e) { stats.missing++; return (BAND_RANK[band] || 0) >= BAND_RANK.B1; }
    var r = e.r || [];
    for (var i = 0; i < r.length; i++) {
      var id = r[i], n = graph.nodes.get(id);
      if (!n || n.kind === 'lexeme') continue;
      if (known.has(id) || (today && today.has(id))) continue;
      if (n.kind === 'grammar' || n.kind === 'contrast') return false;
      if ((n.kind === 'pattern' || n.kind === 'chunk') && firstDay.has(id)) return false;
    }
    return true;
  }

  /* An item targets today when any of its non-lexeme requires is one of today's
   * nodes. The REQUIRES row keeps its requires sorted by kind, not by focus, so
   * "first require" would be an accident of spelling; `f` is a text span, not a node. */
  function targets(key, today) {
    var e = (window.REQUIRES || {})[key];
    if (!e || !today || !today.size) return false;
    var r = e.r || [];
    for (var i = 0; i < r.length; i++) if (today.has(r[i]) && r[i].charAt(1) === ':' && r[i].charAt(0) !== 'l') return true;
    return false;
  }

  return { taughtBy: taughtBy, forLearner: forLearner, todayNodes: todayNodes, introNodes: introNodes, introLesson: introLesson, allows: allows,
           targets: targets, reset: reset, stats: stats,
           firstDay: function (id) { init(); return firstDay.get(id); } };
})();
